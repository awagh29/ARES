function gruEpisode = buildGruEpisode(telemetryPath, outputPath)

    arguments
        telemetryPath (1,1) string
        outputPath (1,1) string = ""
    end

    assert(isfile(telemetryPath), ...
        "ARES:MissingTelemetryFile", ...
        "Telemetry file does not exist: %s", ...
        telemetryPath);

    loadedData = load(telemetryPath);

    assert(isfield(loadedData, "telemetry"), ...
        "ARES:InvalidTelemetryFile", ...
        "MAT file does not contain telemetry.");

    telemetry = loadedData.telemetry;

    %% LiDAR-rate master timeline and paired observations

    [lidarTime_s, nominalObservation] = ...
        readSignal( ...
            telemetry.signals.nominal_observation);

    lidarTime_s = double(lidarTime_s(:));
    numberOfScans = numel(lidarTime_s);

    nominalObservation = samplesByRow( ...
        nominalObservation, ...
        numberOfScans, ...
        "nominal_observation");

    degradedObservation = readAlignedSignal( ...
        telemetry.signals.degraded_observation, ...
        lidarTime_s, ...
        "degraded_observation");

    availabilityMask = logical(readAlignedSignal( ...
        telemetry.signals.observation_availability_mask, ...
        lidarTime_s, ...
        "observation_availability_mask"));

    missingMask = logical(readAlignedSignal( ...
        telemetry.signals.missing_observation_mask, ...
        lidarTime_s, ...
        "missing_observation_mask"));

    nominalValidReturnMask = logical(readAlignedSignal( ...
        telemetry.signals.nominal_lidar_valid_return_mask, ...
        lidarTime_s, ...
        "nominal_lidar_valid_return_mask"));

    assert( ...
        isequal( ...
        size(nominalValidReturnMask), ...
        size(nominalObservation)), ...
        "ARES:ValidReturnMaskSizeMismatch", ...
        "The valid-return mask does not match the observation matrix.");

    degradedValidReturnMask = nominalValidReturnMask & availabilityMask;

    failureActive = logical(readAlignedSignal( ...
        telemetry.signals.lidar_failure_active, ...
        lidarTime_s, ...
        "lidar_failure_active"));

    failureActive = failureActive(:, 1);

    observationDimension = ...
        size(nominalObservation, 2);

    %% Synchronize continuous state variables

    positionNed_m = resampleSignal( ...
        telemetry.signals.position_ned_m, ...
        lidarTime_s, ...
        "linear", ...
        "position_ned_m");

    velocityNed_mps = resampleSignal( ...
        telemetry.signals.velocity_ned_mps, ...
        lidarTime_s, ...
        "linear", ...
        "velocity_ned_mps");

    proprioception = [
        positionNed_m, ...
        velocityNed_mps
        ];
    %% Synchronize goal using zero-order hold

    goalPositionNed_m = resampleSignal( ...
        telemetry.signals.desired_position_ned_m, ...
        lidarTime_s, ...
        "previous", ...
        "desired_position_ned_m");

    %% Synchronize controller actions

    commandRoll = resampleSignal( ...
        telemetry.signals.command_roll_rad, ...
        lidarTime_s, ...
        "previous", ...
        "command_roll_rad");

    commandPitch = resampleSignal( ...
        telemetry.signals.command_pitch_rad, ...
        lidarTime_s, ...
        "previous", ...
        "command_pitch_rad");

    commandYawRate = resampleSignal( ...
        telemetry.signals.command_yaw_rate_radps, ...
        lidarTime_s, ...
        "previous", ...
        "command_yaw_rate_radps");

    commandThrust = resampleSignal( ...
        telemetry.signals.command_thrust_n, ...
        lidarTime_s, ...
        "previous", ...
        "command_thrust_n");

    actionAtScan = [
        commandRoll, ...
        commandPitch, ...
        commandYawRate, ...
        commandThrust
        ];

    assert( ...
        isequal(size(proprioception), ...
        [numberOfScans, 6]), ...
        "ARES:InvalidProprioceptionSize", ...
        "Expected proprioception size [%d 6], received [%d %d].", ...
        numberOfScans, ...
        size(proprioception, 1), ...
        size(proprioception, 2));

    assert( ...
        isequal(size(actionAtScan), ...
        [numberOfScans, 4]), ...
        "ARES:InvalidActionSize", ...
        "Expected action size [%d 4], received [%d %d].", ...
        numberOfScans, ...
        size(actionAtScan, 1), ...
        size(actionAtScan, 2));

    % The recurrent input at time t receives a_(t-1), not a_t.
    previousAction = [
        zeros(1, size(actionAtScan, 2), ...
            "like", actionAtScan)
        actionAtScan(1:end-1, :)
        ];

    %% Validate the canonical episode

    assert( ...
        isequal(size(degradedObservation), ...
            size(nominalObservation)), ...
        "ARES:ObservationSizeMismatch", ...
        "Degraded and nominal observation sizes differ.");

    assert( ...
        isequal(size(availabilityMask), ...
            size(nominalObservation)), ...
        "ARES:AvailabilityMaskSizeMismatch", ...
        "Availability mask size is incorrect.");

    assert( ...
        isequal(size(missingMask), ...
            size(nominalObservation)), ...
        "ARES:MissingMaskSizeMismatch", ...
        "Missing mask size is incorrect.");

    assert( ...
        isequal(availabilityMask, ~missingMask), ...
        "ARES:MaskInconsistency", ...
        "Availability and missing masks are not complements.");

    assert( ...
        isequal(any(missingMask, 2), failureActive), ...
        "ARES:FailureLabelMismatch", ...
        "Failure labels disagree with the missing mask.");

    assert(all(isfinite(degradedObservation), "all"), ...
        "ARES:NonfiniteGruInput", ...
        "Degraded observation contains nonfinite values.");

    assert(all(isfinite(nominalObservation), "all"), ...
        "ARES:NonfiniteGruTarget", ...
        "Nominal observation contains nonfinite values.");

    assert(all(isfinite(proprioception), "all"), ...
        "ARES:NonfiniteProprioception", ...
        "Proprioception contains nonfinite values.");

    assert(all(isfinite(previousAction), "all"), ...
        "ARES:NonfinitePreviousAction", ...
        "Previous actions contain nonfinite values.");

    assert(all(isfinite(goalPositionNed_m), "all"), ...
        "ARES:NonfiniteGoal", ...
        "Goal input contains nonfinite values.");

    %% Preserve separate tensors instead of concatenating them yet

    gruEpisode.schemaVersion = "gru-episode-v1";
    gruEpisode.sourceTelemetryPath = telemetryPath;

    gruEpisode.time_s = lidarTime_s;

    gruEpisode.inputs.degradedObservation = degradedObservation;

    gruEpisode.inputs.availabilityMask = availabilityMask;

    gruEpisode.inputs.proprioception = proprioception;

    gruEpisode.inputs.previousAction = previousAction;

    gruEpisode.inputs.goalPositionNed_m = goalPositionNed_m;

    gruEpisode.targets.nominalObservation = nominalObservation;

    gruEpisode.inputs.degradedValidReturnMask = degradedValidReturnMask;

    gruEpisode.targets.nominalValidReturnMask = nominalValidReturnMask;

    % The reconstruction loss will eventually be evaluated only where this
    % mask is true.
    gruEpisode.targets.lossMask = ...
        missingMask;

    gruEpisode.labels.failureActive = ...
        failureActive;

    gruEpisode.metadata.numberOfScans = ...
        numberOfScans;

    gruEpisode.metadata.observationDimension = ...
        observationDimension;

    gruEpisode.metadata.proprioceptionDimension = ...
        size(proprioception, 2);

    gruEpisode.metadata.actionDimension = ...
        size(previousAction, 2);

    gruEpisode.metadata.goalDimension = ...
        size(goalPositionNed_m, 2);

    gruEpisode.metadata.missingScanCount = ...
        nnz(any(missingMask, 2));

    assert( ...
        isfield(telemetry, "lidarMetadata"), ...
        "ARES:MissingLidarMetadata", ...
        "Telemetry does not contain lidarMetadata.");
    
    assert( ...
        ~any( ...
        degradedValidReturnMask(missingMask), ...
        "all"), ...
        "ARES:ValidReturnDuringOutage", ...
        "The degraded validity mask contains valid returns during an outage.");

    assert( ...
        isequal( ...
        degradedValidReturnMask(availabilityMask), ...
        nominalValidReturnMask(availabilityMask)), ...
        "ARES:HealthyValidityMaskChanged", ...
        "Healthy LiDAR return-validity values were changed.");

    gruEpisode.metadata.gridSize = ...
        telemetry.lidarMetadata.gridSize;

    gruEpisode.metadata.maximumRangeM = ...
        telemetry.lidarMetadata.maximumRangeM;

    gruEpisode.metadata.channelOrder = ...
        telemetry.lidarMetadata.channelOrder;

    gruEpisode.metadata.nominalValidReturnFraction = ...
        nnz(nominalValidReturnMask) ...
        / numel(nominalValidReturnMask);

    %% Save canonical episode

    if strlength(outputPath) == 0
    [sourceFolder, telemetryStem] = fileparts(telemetryPath);

    outputPath = fullfile( ...
        sourceFolder, telemetryStem + "_gru_episode.mat");

    elseif isfolder(outputPath)
        outputPath = fullfile(outputPath, ...
            "intermittent-lidar-single-uav_gru_episode.mat");
    
    else
        [outputFolder, ~, outputExtension] = fileparts(outputPath);
    
        if strlength(outputExtension) == 0
            if ~isfolder(outputPath)
                mkdir(outputPath);
            end
    
            outputPath = fullfile(outputPath, ...
                "intermittent-lidar-single-uav_gru_episode.mat");
    
        elseif strlength(outputFolder) > 0 && ...
                ~isfolder(outputFolder)
    
            mkdir(outputFolder);
        end
    end

    save(outputPath, "gruEpisode", "-v7.3");

    fprintf("\nCanonical GRU episode created.\n");
    fprintf("Scans: %d\n", numberOfScans);
    fprintf("Observation dimension: %d\n", ...
        observationDimension);
    fprintf("Proprioception dimension: %d\n", ...
        size(proprioception, 2));
    fprintf("Previous-action dimension: %d\n", ...
        size(previousAction, 2));
    fprintf("Goal dimension: %d\n", ...
        size(goalPositionNed_m, 2));
    fprintf("Missing scans: %d\n", ...
        gruEpisode.metadata.missingScanCount);
    fprintf("Saved to: %s\n", outputPath);

    fprintf("Nominal valid-return fraction: %.6f\n", ...
        gruEpisode.metadata.nominalValidReturnFraction);
end

function alignedValues = readAlignedSignal( ...
        signal, masterTime_s, signalName)

    [signalTime_s, values] = readSignal(signal);

    signalTime_s = double(signalTime_s(:));

    values = samplesByRow( ...
        values, ...
        numel(signalTime_s), ...
        signalName);

    assert( ...
        numel(signalTime_s) == numel(masterTime_s), ...
        "ARES:AlignedSignalLengthMismatch", ...
        "Signal %s does not have the LiDAR sample count.", ...
        signalName);

    assert( ...
        max(abs(signalTime_s - masterTime_s)) <= 1e-9, ...
        "ARES:AlignedSignalTimeMismatch", ...
        "Signal %s is not aligned to LiDAR timestamps.", ...
        signalName);

    alignedValues = values;
end

function sampledValues = resampleSignal( ...
        signal, targetTime_s, method, signalName)

    [sourceTime_s, sourceValues] = ...
        readSignal(signal);

    sourceTime_s = double(sourceTime_s(:));

    sourceValues = samplesByRow( ...
        sourceValues, ...
        numel(sourceTime_s), ...
        signalName);

    % Remove duplicate solver timestamps while retaining the latest value.
    [sourceTime_s, uniqueIndices] = ...
        unique(sourceTime_s, "last");

    sourceValues = ...
        sourceValues(uniqueIndices, :);

    assert( ...
        targetTime_s(1) >= sourceTime_s(1) - 1e-9 && ...
        targetTime_s(end) <= sourceTime_s(end) + 1e-9, ...
        "ARES:ResamplingOutsideTimeRange", ...
        "Signal %s does not cover the LiDAR time range.", ...
        signalName);

    sampledValues = interp1( ...
        sourceTime_s, ...
        double(sourceValues), ...
        targetTime_s, ...
        method);

    assert( ...
        all(isfinite(sampledValues), "all"), ...
        "ARES:ResamplingProducedNonfiniteValues", ...
        "Resampling %s produced nonfinite values.", ...
        signalName);
end

function [time_s, values] = readSignal(signal)

    if isa(signal, "timeseries")
        time_s = double(signal.Time(:));
        values = signal.Data;
        return;
    end

    timeCandidates = [
        "time_s"
        "time"
        "timestamps_s"
        ];

    valueCandidates = [
        "values"
        "data"
        "samples"
        "value"
        ];

    time_s = [];
    values = [];

    for index = 1:numel(timeCandidates)
        fieldName = timeCandidates(index);

        if isfield(signal, fieldName)
            time_s = double(signal.(fieldName)(:));
            break;
        end
    end

    for index = 1:numel(valueCandidates)
        fieldName = valueCandidates(index);

        if isfield(signal, fieldName)
            values = signal.(fieldName);
            break;
        end
    end

    assert(~isempty(time_s), ...
        "ARES:MissingSignalTime", ...
        "Could not locate signal timestamps.");

    assert(~isempty(values), ...
        "ARES:MissingSignalValues", ...
        "Could not locate signal values.");
end

function values = samplesByRow( ...
        values, expectedSamples, signalName)

    values = squeeze(values);

    if isvector(values)
        values = values(:);
    end

    if size(values, 1) == expectedSamples
        return;
    end

    if size(values, 2) == expectedSamples
        values = values.';
        return;
    end

    error( ...
        "ARES:SignalOrientationMismatch", ...
        "Could not orient %s into %d samples.", ...
        signalName, ...
        expectedSamples);
end