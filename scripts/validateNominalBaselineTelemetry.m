function report = validateNominalBaselineTelemetry(telemetryPath)
%VALIDATENOMINALBASELINETELEMETRY
% Validates and visualizes one ARES nominal-baseline dataset.

if nargin < 1 || strlength(string(telemetryPath)) == 0

    proj = currentProject;
    projectRoot = string(proj.RootFolder);

    telemetryFiles = dir(fullfile( ...
        projectRoot, ...
        "data", ...
        "raw", ...
        "**", ...
        "*_telemetry.mat"));

    assert( ...
        ~isempty(telemetryFiles), ...
        "ARES:NoTelemetryFiles", ...
        "No telemetry MAT files were found.");

    [~, newestIndex] = max( ...
        [telemetryFiles.datenum]);

    telemetryPath = fullfile( ...
        telemetryFiles(newestIndex).folder, ...
        telemetryFiles(newestIndex).name);
end

telemetryPath = string(telemetryPath);

assert( ...
    isfile(telemetryPath), ...
    "ARES:MissingTelemetryFile", ...
    "Telemetry file does not exist: %s", ...
    telemetryPath);

fprintf("Validating:\n%s\n\n", telemetryPath);

loadedData = load(telemetryPath);

if isfield(loadedData, "telemetry")
    telemetry = loadedData.telemetry;
else
    loadedNames = fieldnames(loadedData);
    telemetry = [];

    for variableIndex = 1:numel(loadedNames)
        candidate = loadedData.(loadedNames{variableIndex});

        if isstruct(candidate) && ...
                isfield(candidate, "signals")
            telemetry = candidate;
            break;
        end
    end

    assert( ...
        ~isempty(telemetry), ...
        "ARES:TelemetryVariableNotFound", ...
        "No telemetry structure was found in the MAT file.");
end

requiredSignals = [
    "nominal_lidar_ranges_m"
    "nominal_lidar_valid_return_mask"
    "nominal_observation"
    "position_ned_m"
    ];

availableSignals = string( ...
    fieldnames(telemetry.signals));

missingSignals = setdiff( ...
    requiredSignals, ...
    availableSignals);

assert( ...
    isempty(missingSignals), ...
    "ARES:MissingValidationSignals", ...
    "Missing signals: %s", ...
    strjoin(missingSignals, ", "));

%% Read matrices

[lidarTime, ranges] = localReadSignal( ...
    telemetry.signals.nominal_lidar_ranges_m);

[maskTime, maskRaw] = localReadSignal( ...
    telemetry.signals.nominal_lidar_valid_return_mask);

[observationTime, nominalObservation] = ...
    localReadSignal( ...
        telemetry.signals.nominal_observation);

validMask = logical(maskRaw);

numberOfScans = size(ranges, 1);
observationDimension = size(ranges, 2);

gridSize = double( ...
    telemetry.lidarMetadata.gridSize);

maximumRangeM = double( ...
    telemetry.lidarMetadata.maximumRangeM);

assert( ...
    isequal(size(validMask), size(ranges)), ...
    "ARES:MaskSizeMismatch", ...
    "Validity mask and range matrix sizes differ.");

assert( ...
    isequal(size(nominalObservation), size(ranges)), ...
    "ARES:ObservationSizeMismatch", ...
    "Nominal observation and range matrix sizes differ.");

assert( ...
    prod(gridSize) == observationDimension, ...
    "ARES:GridDimensionMismatch", ...
    "LiDAR grid does not match the observation dimension.");

assert( ...
    numel(lidarTime) == numberOfScans, ...
    "ARES:TimestampCountMismatch", ...
    "LiDAR timestamp count does not match scan count.");

assert( ...
    all(diff(lidarTime) > 0), ...
    "ARES:NonMonotonicLidarTime", ...
    "LiDAR timestamps are not strictly increasing.");

timestampTolerance = 1e-9;

assert( ...
    max(abs(lidarTime - maskTime)) <= ...
        timestampTolerance, ...
    "ARES:MaskTimestampMismatch", ...
    "Mask and range timestamps differ.");

assert( ...
    max(abs(lidarTime - observationTime)) <= ...
        timestampTolerance, ...
    "ARES:ObservationTimestampMismatch", ...
    "Observation and range timestamps differ.");

assert( ...
    all(isfinite(ranges), "all"), ...
    "ARES:NonfiniteRangeMatrix", ...
    "Completed range matrix contains nonfinite values.");

assert( ...
    all(ranges >= 0, "all") && ...
    all(ranges <= maximumRangeM, "all"), ...
    "ARES:RangeBoundViolation", ...
    "Range values fall outside [0, MaxRange].");

assert( ...
    max(abs( ...
        nominalObservation(:) - ranges(:))) <= 1e-12, ...
    "ARES:ObservationMismatch", ...
    "The LiDAR-only nominal observation must equal the range matrix.");

invalidRanges = ranges(~validMask);

assert( ...
    all(abs(invalidRanges - maximumRangeM) <= 1e-9), ...
    "ARES:InvalidReturnEncoding", ...
    "Invalid returns are not encoded using maximum range.");

validRanges = ranges(validMask);

assert( ...
    all(validRanges > 0) && ...
    all(validRanges <= maximumRangeM), ...
    "ARES:InvalidValidReturn", ...
    "Valid-return ranges violate expected bounds.");

%% Summary metrics

sampleIntervals = diff(lidarTime);

validReturnCount = nnz(validMask);
totalBeamCount = numel(validMask);
validReturnFraction = ...
    validReturnCount / totalBeamCount;

validReturnsPerScan = sum(validMask, 2);
validFractionPerScan = ...
    validReturnsPerScan / observationDimension;

minimumValidRangePerScan = ...
    NaN(numberOfScans, 1);

medianValidRangePerScan = ...
    NaN(numberOfScans, 1);

meanValidRangePerScan = ...
    NaN(numberOfScans, 1);

for scanIndex = 1:numberOfScans

    scanValues = ranges( ...
        scanIndex, ...
        validMask(scanIndex, :));

    if ~isempty(scanValues)
        minimumValidRangePerScan(scanIndex) = ...
            min(scanValues);

        medianValidRangePerScan(scanIndex) = ...
            median(scanValues);

        meanValidRangePerScan(scanIndex) = ...
            mean(scanValues);
    end
end

summaryTable = table( ...
    numberOfScans, ...
    observationDimension, ...
    median(sampleIntervals), ...
    maximumRangeM, ...
    validReturnCount, ...
    totalBeamCount, ...
    validReturnFraction, ...
    min(validRanges), ...
    median(validRanges), ...
    max(validRanges), ...
    VariableNames=[ ...
        "NumberOfScans", ...
        "ObservationDimension", ...
        "MedianSampleTimeS", ...
        "MaximumRangeM", ...
        "ValidReturnCount", ...
        "TotalBeamCount", ...
        "ValidReturnFraction", ...
        "MinimumValidRangeM", ...
        "MedianValidRangeM", ...
        "MaximumValidRangeM"]);

disp("Nominal baseline validation summary:");
disp(summaryTable);

fprintf( ...
    "Maximum estimable covariance rank: %d\n", ...
    numberOfScans - 1);

fprintf( ...
    "Observation dimension: %d\n", ...
    observationDimension);

fprintf( ...
    "Invalid/no-return fraction: %.4f\n", ...
    1 - validReturnFraction);

%% Per-channel statistics

validCountPerChannel = sum(validMask, 1);

validFractionPerChannel = ...
    validCountPerChannel / numberOfScans;

maskedRanges = ranges .* double(validMask);

rangeSumPerChannel = sum( ...
    maskedRanges, ...
    1);

rangeSquareSumPerChannel = sum( ...
    maskedRanges.^2, ...
    1);

meanRangePerChannel = ...
    rangeSumPerChannel ./ ...
    validCountPerChannel;

varianceNumerator = ...
    rangeSquareSumPerChannel - ...
    validCountPerChannel .* ...
    meanRangePerChannel.^2;

varianceRangePerChannel = ...
    varianceNumerator ./ ...
    max(validCountPerChannel - 1, 1);

standardDeviationPerChannel = sqrt( ...
    max(varianceRangePerChannel, 0));

meanRangePerChannel( ...
    validCountPerChannel == 0) = NaN;

standardDeviationPerChannel( ...
    validCountPerChannel < 2) = NaN;

%% Select a representative beam

eligibleChannels = ...
    validCountPerChannel >= 30 & ...
    standardDeviationPerChannel > 1e-6;

if any(eligibleChannels)

    eligibleIndices = find(eligibleChannels);

    [~, bestLocalIndex] = max( ...
        validCountPerChannel(eligibleChannels));

    representativeChannel = ...
        eligibleIndices(bestLocalIndex);

else
    [~, representativeChannel] = max( ...
        validCountPerChannel);
end

[elevationIndex, azimuthIndex] = ind2sub( ...
    gridSize, ...
    representativeChannel);

representativeValues = ranges( ...
    validMask(:, representativeChannel), ...
    representativeChannel);

representativeMean = mean( ...
    representativeValues);

representativeStandardDeviation = std( ...
    representativeValues);

%% Low-rank variance analysis

% This avoids constructing a 10740-by-10740 covariance matrix.
centeredObservations = single(ranges);

centeredObservations = ...
    centeredObservations - ...
    mean(centeredObservations, 1);

sampleGramMatrix = double( ...
    centeredObservations * ...
    centeredObservations');

sampleGramMatrix = ...
    (sampleGramMatrix + ...
     sampleGramMatrix') / 2;

eigenvalues = sort( ...
    eig(sampleGramMatrix), ...
    "descend");

eigenvalues = max(eigenvalues, 0);

if sum(eigenvalues) > 0
    cumulativeExplainedVariance = ...
        cumsum(eigenvalues) / ...
        sum(eigenvalues);
else
    cumulativeExplainedVariance = ...
        zeros(size(eigenvalues));
end

%% Output directory

runDirectory = string( ...
    fileparts(telemetryPath));

validationDirectory = fullfile( ...
    runDirectory, ...
    "validation");

if ~isfolder(validationDirectory)
    mkdir(validationDirectory);
end

%% Figure 1: scan-level validation

representativeScan = round(numberOfScans / 2);

rangeGrid = reshape( ...
    ranges(representativeScan, :), ...
    gridSize);

maskGrid = reshape( ...
    validMask(representativeScan, :), ...
    gridSize);

scanFigure = figure( ...
    Name="Nominal LiDAR Scan Validation", ...
    Color="white");

scanLayout = tiledlayout( ...
    scanFigure, ...
    2, ...
    2, ...
    TileSpacing="compact", ...
    Padding="compact");

nexttile(scanLayout);

imagesc( ...
    1:gridSize(2), ...
    1:gridSize(1), ...
    rangeGrid);

axis xy;
colorbar;
clim([0 maximumRangeM]);

xlabel("Azimuth index");
ylabel("Elevation index");

title(sprintf( ...
    "Range scan %d at %.2f s", ...
    representativeScan, ...
    lidarTime(representativeScan)));

nexttile(scanLayout);

imagesc( ...
    1:gridSize(2), ...
    1:gridSize(1), ...
    maskGrid);

axis xy;
colorbar;
clim([0 1]);

xlabel("Azimuth index");
ylabel("Elevation index");
title("Valid-return mask");

nexttile(scanLayout);

plot( ...
    lidarTime, ...
    validFractionPerScan, ...
    LineWidth=1.3);

grid on;
ylim([0 1]);

xlabel("Simulation time (s)");
ylabel("Valid-return fraction");
title("LiDAR coverage over time");

nexttile(scanLayout);

plot( ...
    lidarTime, ...
    minimumValidRangePerScan, ...
    LineWidth=1.2);

hold on;

plot( ...
    lidarTime, ...
    medianValidRangePerScan, ...
    LineWidth=1.2);

plot( ...
    lidarTime, ...
    meanValidRangePerScan, ...
    LineWidth=1.2);

hold off;
grid on;

xlabel("Simulation time (s)");
ylabel("Range (m)");

legend( ...
    "Minimum", ...
    "Median", ...
    "Mean", ...
    Location="best");

title("Valid-return range statistics");

exportgraphics( ...
    scanFigure, ...
    fullfile( ...
        validationDirectory, ...
        "lidar_scan_validation.png"), ...
    Resolution=200);

%% Figure 2: channel statistics and Gaussian baseline

statisticsFigure = figure( ...
    Name="LiDAR Statistical Baseline", ...
    Color="white");

statisticsLayout = tiledlayout( ...
    statisticsFigure, ...
    2, ...
    2, ...
    TileSpacing="compact", ...
    Padding="compact");

nexttile(statisticsLayout);

imagesc(reshape( ...
    validFractionPerChannel, ...
    gridSize));

axis xy;
colorbar;
clim([0 1]);

xlabel("Azimuth index");
ylabel("Elevation index");
title("Per-beam valid-return probability");

nexttile(statisticsLayout);

imagesc(reshape( ...
    meanRangePerChannel, ...
    gridSize));

axis xy;
colorbar;
clim([0 maximumRangeM]);

xlabel("Azimuth index");
ylabel("Elevation index");
title("Mean range conditional on valid return");

nexttile(statisticsLayout);

histogram( ...
    representativeValues, ...
    25, ...
    Normalization="pdf");

hold on;

if representativeStandardDeviation > 0

    gaussianX = linspace( ...
        min(representativeValues), ...
        max(representativeValues), ...
        200);

    gaussianY = ...
        exp(-0.5 * ...
        ((gaussianX - representativeMean) ./ ...
        representativeStandardDeviation).^2) ./ ...
        (representativeStandardDeviation * sqrt(2*pi));

    plot( ...
        gaussianX, ...
        gaussianY, ...
        LineWidth=1.5);
end

hold off;
grid on;

xlabel("Range (m)");
ylabel("Probability density");

title(sprintf( ...
    "Beam e%d/a%d: conditional Gaussian fit", ...
    elevationIndex, ...
    azimuthIndex));

legend( ...
    "Empirical", ...
    "Gaussian", ...
    Location="best");

nexttile(statisticsLayout);

numberOfComponentsToShow = min( ...
    50, ...
    numel(cumulativeExplainedVariance));

plot( ...
    1:numberOfComponentsToShow, ...
    cumulativeExplainedVariance( ...
        1:numberOfComponentsToShow), ...
    LineWidth=1.5);

grid on;
ylim([0 1]);

xlabel("Number of components");
ylabel("Cumulative explained variance");
title("Low-rank observation structure");

exportgraphics( ...
    statisticsFigure, ...
    fullfile( ...
        validationDirectory, ...
        "lidar_statistical_baseline.png"), ...
    Resolution=200);

%% Figure 3: trajectory

trajectoryFigurePath = "";

try
    [~, positionNed] = localReadSignal( ...
        telemetry.signals.position_ned_m);

    trajectoryFigure = figure( ...
        Name="Nominal UAV Trajectory", ...
        Color="white");

    plot( ...
        positionNed(:, 2), ...
        positionNed(:, 1), ...
        LineWidth=1.5);

    hold on;

    scatter( ...
        positionNed(1, 2), ...
        positionNed(1, 1), ...
        60, ...
        "filled");

    scatter( ...
        positionNed(end, 2), ...
        positionNed(end, 1), ...
        60, ...
        "filled");

    if isfield( ...
            telemetry.signals, ...
            "desired_position_ned_m")

        [~, desiredPosition] = localReadSignal( ...
            telemetry.signals.desired_position_ned_m);

        plot( ...
            desiredPosition(:, 2), ...
            desiredPosition(:, 1), ...
            "--", ...
            LineWidth=1);
    end

    hold off;
    axis equal;
    grid on;

    xlabel("East (m)");
    ylabel("North (m)");
    title("Nominal top-down trajectory");

    legend( ...
        "Executed trajectory", ...
        "Start", ...
        "End", ...
        "Desired trajectory", ...
        Location="best");

    trajectoryFigurePath = fullfile( ...
        validationDirectory, ...
        "nominal_trajectory.png");

    exportgraphics( ...
        trajectoryFigure, ...
        trajectoryFigurePath, ...
        Resolution=200);

catch trajectoryError
    warning( ...
        "ARES:TrajectoryPlotFailed", ...
        "Trajectory plot was skipped: %s", ...
        trajectoryError.message);
end

%% Report

report.telemetryPath = telemetryPath;
report.validationDirectory = ...
    string(validationDirectory);

report.summary = summaryTable;

report.representativeBeam = struct( ...
    "linearIndex", representativeChannel, ...
    "elevationIndex", elevationIndex, ...
    "azimuthIndex", azimuthIndex, ...
    "validSampleCount", ...
        numel(representativeValues), ...
    "meanRangeM", representativeMean, ...
    "standardDeviationM", ...
        representativeStandardDeviation);

report.maximumCovarianceRank = ...
    numberOfScans - 1;

report.cumulativeExplainedVariance = ...
    cumulativeExplainedVariance;

report.figurePaths = struct( ...
    "scanValidation", ...
        string(fullfile( ...
            validationDirectory, ...
            "lidar_scan_validation.png")), ...
    "statisticalBaseline", ...
        string(fullfile( ...
            validationDirectory, ...
            "lidar_statistical_baseline.png")), ...
    "trajectory", ...
        string(trajectoryFigurePath));

save( ...
    fullfile( ...
        validationDirectory, ...
        "nominal_validation_report.mat"), ...
    "report");

fprintf("\nPASS: Nominal telemetry validated.\n");
fprintf("Validation outputs:\n%s\n", ...
    validationDirectory);

end

function [time, data] = localReadSignal(signal)

if isa(signal, "timeseries")
    time = double(signal.Time(:));
    data = signal.Data;
    data = localOrientSamples(data, numel(time));
    return;
end

assert( ...
    isstruct(signal), ...
    "ARES:InvalidSignalRepresentation", ...
    "Expected a signal structure or timeseries.");

signalFields = string(fieldnames(signal));

timeCandidates = [
    "time_s"
    "time"
    "timestamps_s"
    "timestamps"
    "Time"
    ];

dataCandidates = [
    "values"
    "data"
    "samples"
    "value"
    "Data"
    ];

timeField = "";
dataField = "";

for candidate = timeCandidates'
    matchIndex = find( ...
        strcmpi(signalFields, candidate), ...
        1);

    if ~isempty(matchIndex)
        timeField = signalFields(matchIndex);
        break;
    end
end

for candidate = dataCandidates'
    matchIndex = find( ...
        strcmpi(signalFields, candidate), ...
        1);

    if ~isempty(matchIndex)
        dataField = signalFields(matchIndex);
        break;
    end
end

if strlength(timeField) == 0 || ...
        strlength(dataField) == 0

    error( ...
        "ARES:UnknownSignalStructure", ...
        "Could not identify time/data fields. Fields: %s", ...
        strjoin(signalFields, ", "));
end

time = double(signal.(char(timeField))(:));
data = signal.(char(dataField));

data = localOrientSamples( ...
    data, ...
    numel(time));

end

function data = localOrientSamples(data, numberOfSamples)

data = squeeze(data);

if isvector(data) && ...
        numel(data) == numberOfSamples
    data = reshape(data, numberOfSamples, 1);
    return;
end

if size(data, 1) == numberOfSamples
    return;
end

if size(data, 2) == numberOfSamples
    data = data';
    return;
end

error( ...
    "ARES:CannotOrientSignal", ...
    "Cannot orient data of size %s around %d timestamps.", ...
    mat2str(size(data)), ...
    numberOfSamples);

end