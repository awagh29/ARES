function auditGruTelemetry( ...
        nominalTelemetryPath, ...
        intermittentTelemetryPath)

    nominal = loadTelemetry(nominalTelemetryPath);
    intermittent = loadTelemetry(intermittentTelemetryPath);

    %% Read core paired observations

    [nominalTime_s, nominalObservation] = readSignal( ...
        nominal.signals.nominal_observation);

    [intermittentTime_s, intermittentTarget] = readSignal( ...
        intermittent.signals.nominal_observation);

    [~, degradedObservation] = readSignal( ...
        intermittent.signals.degraded_observation);

    [~, missingMask] = readSignal( ...
        intermittent.signals.missing_observation_mask);

    [~, availabilityMask] = readSignal( ...
        intermittent.signals.observation_availability_mask);

    [~, missingGroundTruth] = readSignal( ...
        intermittent.signals.missing_observation_ground_truth);

    [~, failureActive] = readSignal( ...
        intermittent.signals.lidar_failure_active);

    %% Normalize orientation

    nominalObservation = samplesByRow( ...
        nominalObservation, ...
        numel(nominalTime_s), ...
        "nominal observation");

    intermittentTarget = samplesByRow( ...
        intermittentTarget, ...
        numel(intermittentTime_s), ...
        "intermittent target");

    degradedObservation = samplesByRow( ...
        degradedObservation, ...
        numel(intermittentTime_s), ...
        "degraded observation");

    missingMask = logical(samplesByRow( ...
        missingMask, ...
        numel(intermittentTime_s), ...
        "missing mask"));

    availabilityMask = logical(samplesByRow( ...
        availabilityMask, ...
        numel(intermittentTime_s), ...
        "availability mask"));

    missingGroundTruth = samplesByRow( ...
        missingGroundTruth, ...
        numel(intermittentTime_s), ...
        "missing ground truth");

    failureActive = logical(samplesByRow( ...
        failureActive, ...
        numel(intermittentTime_s), ...
        "failure active"));

    failureActive = failureActive(:, 1);

    %% Shape and time checks

    nominalSize = size(nominalObservation);
    intermittentSize = size(intermittentTarget);

    assert( ...
        nominalSize(2) == intermittentSize(2), ...
        "ARES:ObservationSchemaDrift", ...
        "Nominal width is %d but intermittent width is %d.", ...
        nominalSize(2), ...
        intermittentSize(2));

    assert( ...
        all(diff(nominalTime_s) > 0), ...
        "ARES:InvalidNominalTime", ...
        "Nominal timestamps are not strictly increasing.");

    assert( ...
        all(diff(intermittentTime_s) > 0), ...
        "ARES:InvalidIntermittentTime", ...
        "Intermittent timestamps are not strictly increasing.");

    expectedSize = size(intermittentTarget);

    assert( ...
        isequal(size(degradedObservation), expectedSize), ...
        "ARES:DegradedObservationSizeMismatch", ...
        "Degraded observation and target dimensions differ.");

    assert( ...
        isequal(size(missingMask), expectedSize), ...
        "ARES:MissingMaskSizeMismatch", ...
        "Missing mask and target dimensions differ.");

    assert( ...
        isequal(size(availabilityMask), expectedSize), ...
        "ARES:AvailabilityMaskSizeMismatch", ...
        "Availability mask and target dimensions differ.");

    assert( ...
        isequal(size(missingGroundTruth), expectedSize), ...
        "ARES:GroundTruthSizeMismatch", ...
        "Missing ground truth and target dimensions differ.");

    %% Pair-integrity checks

    assert( ...
        isequal(missingMask, ~availabilityMask), ...
        "ARES:MaskInconsistency", ...
        "Missing and availability masks are not complements.");

    outageRows = ...
        any(missingMask, 2);

    assert( ...
        isequal(outageRows, failureActive), ...
        "ARES:FaultLabelMismatch", ...
        "Fault labels disagree with the missing-observation mask.");

    assert( ...
        all( ...
            all(missingMask, 2) | ...
            ~any(missingMask, 2)), ...
        "ARES:UnexpectedPartialMissingness", ...
        ["The current experiment should contain complete-scan " + ...
         "outages, but partial masks were found."]);

    assert( ...
        all( ...
            degradedObservation(~missingMask) == ...
            intermittentTarget(~missingMask)), ...
        "ARES:HealthyDataChanged", ...
        "Healthy observations differ from their nominal targets.");

    assert( ...
        all( ...
            missingGroundTruth(missingMask) == ...
            intermittentTarget(missingMask)), ...
        "ARES:IncorrectReconstructionTarget", ...
        "Missing-observation ground truth does not match the oracle target.");

    %% Data-quality measurements

    numberOfNominalScans = ...
        size(nominalObservation, 1);

    numberOfIntermittentScans = ...
        size(intermittentTarget, 1);

    observationDimension = ...
        size(intermittentTarget, 2);

    missingScanCount = ...
        nnz(outageRows);

    missingValueCount = ...
        nnz(missingMask);

    missingValueFraction = ...
        missingValueCount / numel(missingMask);

    finiteTargetFraction = ...
        nnz(isfinite(intermittentTarget)) ...
        / numel(intermittentTarget);

    finiteInputFraction = ...
        nnz(isfinite(degradedObservation)) ...
        / numel(degradedObservation);

    summaryTable = table( ...
        numberOfNominalScans, ...
        numberOfIntermittentScans, ...
        observationDimension, ...
        missingScanCount, ...
        missingValueCount, ...
        missingValueFraction, ...
        finiteTargetFraction, ...
        finiteInputFraction);

    fprintf("\nGRU paired-data audit:\n");
    disp(summaryTable);

    fprintf( ...
        "Nominal time range: %.3f to %.3f s\n", ...
        nominalTime_s(1), ...
        nominalTime_s(end));

    fprintf( ...
        "Intermittent time range: %.3f to %.3f s\n", ...
        intermittentTime_s(1), ...
        intermittentTime_s(end));

    fprintf( ...
        "PASS: Intermittent observations form valid paired examples.\n");
end

function telemetry = loadTelemetry(telemetryPath)

    assert( ...
        isfile(telemetryPath), ...
        "ARES:MissingTelemetryFile", ...
        "Telemetry file does not exist: %s", ...
        telemetryPath);

    loadedData = load(telemetryPath);

    assert( ...
        isfield(loadedData, "telemetry"), ...
        "ARES:InvalidTelemetryFile", ...
        "The MAT file does not contain telemetry.");

    telemetry = loadedData.telemetry;

    assert( ...
        isfield(telemetry, "signals"), ...
        "ARES:MissingSignals", ...
        "Telemetry does not contain a signals structure.");
end

function [time_s, values] = readSignal(signal)

    if isa(signal, "timeseries")
        time_s = double(signal.Time(:));
        values = signal.Data;
        return;
    end

    timeCandidates = [
        "time_s"
        "time"
        "timestamps_s"
        ];

    valueCandidates = [
        "values"
        "data"
        "samples"
        "value"
        ];

    time_s = [];
    values = [];

    for index = 1:numel(timeCandidates)
        fieldName = timeCandidates(index);

        if isfield(signal, fieldName)
            time_s = double(signal.(fieldName)(:));
            break;
        end
    end

    for index = 1:numel(valueCandidates)
        fieldName = valueCandidates(index);

        if isfield(signal, fieldName)
            values = signal.(fieldName);
            break;
        end
    end

    assert( ...
        ~isempty(time_s), ...
        "ARES:MissingSignalTime", ...
        "Could not locate signal timestamps.");

    assert( ...
        ~isempty(values), ...
        "ARES:MissingSignalValues", ...
        "Could not locate signal values.");
end

function values = samplesByRow( ...
        values, expectedSamples, signalName)

    values = squeeze(values);

    if size(values, 1) == expectedSamples
        return;
    end

    if size(values, 2) == expectedSamples
        values = values.';
        return;
    end

    error( ...
        "ARES:SignalOrientationMismatch", ...
        "Could not orient %s into %d samples.", ...
        signalName, ...
        expectedSamples);
end