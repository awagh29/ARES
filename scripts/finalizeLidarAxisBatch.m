    "minimumSurfaceClearanceM",metrics.minimumObstacleClearanceM, ...
    "allDataChecksPassed",true);
end

function checkFiniteEpisode(value,path,context)
if isstruct(value)
    names = fieldnames(value);
    for index = 1:numel(names)
        name = string(names{index});
        checkFiniteEpisode(value.(name),path+"."+name,context);
    end
elseif isnumeric(value) || islogical(value)
    require(isreal(value),context+"complex episode field "+path);
    if path=="episode.action.previous"
        require(size(value,1)>=2 && all(isnan(value(1,:))) && ...
            all(isfinite(double(value(2:end,:))),"all"), ...
            context+"unexpected unavailable values in previous actions.");
    else
        require(all(isfinite(double(value)),"all"),context+"nonfinite episode field "+path);
    end
end
end

function values = sampleNative(signal,queryTime,method)
time = double(signal.time_s(:));
[time,last] = unique(time,"last");
native = double(signal.values(last,:));
require(queryTime(1)>=time(1)-1e-9 && queryTime(end)<=time(end)+1e-9, ...
    "Native signal does not cover the complete scan timeline.");
queryTime=min(max(queryTime,time(1)),time(end));
if method=="angular"
    values = interp1(time,unwrap(native,[],1),queryTime,"linear");
    values = atan2(sin(values),cos(values));
else
    values = interp1(time,native,queryTime,method);
end
end

function assertClose(actual,expected,tolerance,description)
require(isequal(size(actual),size(expected)) && all(isfinite(actual),"all") && ...
    all(isfinite(expected),"all") && all(abs(actual-expected)<=tolerance,"all"), ...
    description+" differs from its verified source.");
end

