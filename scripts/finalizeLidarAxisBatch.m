function index = finalizeLidarAxisBatch(batchPath)
%FINALIZELIDARAXISBATCH Merge worker checkpoints and audit all 80 saved runs.
% Raw and processed per-run artifacts are read only. The merged index,
% all_scans.csv and QA/summary reports are replaced atomically after validation.
% A failed audit writes dataset_qa.json with the exact failure then rethrows.
arguments
    batchPath (1,1) string
end
qa = struct("schemaVersion","lidar-axis-dataset-qa-v1", ...
    "allDataChecksPassed",false,"checkedAtUtc",utcNow(), ...
    "collisionDetectionMethod", ...
    "signed-3d-box-distance-at-native-position-samples; not a continuous collision proof");
try
    saved = load(fullfile(batchPath,"plan.mat"),"plan","metadata");
    plan = saved.plan; metadata = saved.metadata;
    metadata.authorizedSourceSnapshots={metadata.sourceSnapshot};
    amendmentFiles=dir(fullfile(batchPath,"source_amendment_*.mat"));
    expectedSnapshot=metadata.sourceSnapshot;
    for amendmentIndex=1:numel(amendmentFiles)
        record=load(fullfile(amendmentFiles(amendmentIndex).folder,amendmentFiles(amendmentIndex).name),"amendment");
        amendment=record.amendment;
        require(string(amendment.batchId)==string(metadata.batchId) && ...
            isequal(amendment.fromSnapshot,expectedSnapshot),"Invalid source amendment chain.");
        expectedSnapshot=amendment.toSnapshot;
        metadata.authorizedSourceSnapshots{end+1}=expectedSnapshot;
    end
    qa.sourceAmendmentCount=numel(amendmentFiles);
    qa.batchId = string(metadata.batchId);
    validatePlan(plan);
    checkpointFiles = [dir(fullfile(batchPath,"checkpoint.mat")); ...
        dir(fullfile(batchPath,"checkpoint_worker*.mat"))];
    require(~isempty(checkpointFiles),"No batch checkpoint was found.");
    base = load(fullfile(batchPath,"checkpoint.mat"),"index");
    index = base.index;
    require(height(index)==80,"Authoritative checkpoint must contain 80 rows.");
    require(isequal(index.RunIndex,plan.RunIndex),"Checkpoint row ordering differs from plan.");
    completed = false(80,1);
    selected = index;
    identicalInheritedRows = 0;
    for fileIndex = 1:numel(checkpointFiles)
        file = checkpointFiles(fileIndex);
        state = load(fullfile(file.folder,file.name),"index");
        candidate = state.index;
        require(istable(candidate) && height(candidate)==80, ...
            "Worker checkpoint must contain the full 80-row index: "+file.name);
        require(isequal(candidate.Properties.VariableNames,index.Properties.VariableNames), ...
            "Worker checkpoint schema differs: "+file.name);
        require(isequal(candidate(:,plan.Properties.VariableNames),plan), ...
            "Worker checkpoint changes the frozen plan: "+file.name);
        rows = find(string(candidate.Status)=="complete");
        for row = rows'
            require(strlength(string(candidate.RunId(row)))>0, ...
                "Completed run has an empty RunId.");
            if completed(row)
                require(isequaln(candidate(row,:),selected(row,:)), ...
                    "Conflicting completed checkpoints for RunIndex "+row+".");
                identicalInheritedRows = identicalInheritedRows+1;
            else
                selected(row,:) = candidate(row,:);
                completed(row) = true;
            end
        end
    end
    require(all(completed),"Expected 80 completed runs; found "+nnz(completed)+".");
    index = selected;
    require(numel(unique(string(index.RunId)))==80,"Duplicate completed RunIds were found.");
    require(isequal(index(:,plan.Properties.VariableNames),plan), ...
        "Merged index changes the frozen plan.");
    allScans = table();
    runQa = struct([]);
    for row = 1:80
        [scan,thisRunQa] = auditRun(index(row,:),plan(row,:),metadata);
        if row==1
            runQa = repmat(thisRunQa,80,1);
        else
            runQa(row) = thisRunQa;
        end
        scan.RunIndex = repmat(row,height(scan),1);
        scan.BatchId = repmat(string(metadata.batchId),height(scan),1);
        if row==1
            allScans = scan;
        else
            require(isequal(allScans.Properties.VariableNames,scan.Properties.VariableNames), ...
                "Per-run scan CSV schemas differ.");
            allScans = [allScans;scan]; %#ok<AGROW>
        end
        fprintf("QA_RUN %d/80 id=%s scans=%d success=%d collision=%d\n", ...
            row,index.RunId(row),height(scan),index.MissionSuccess(row),index.CollisionOccurred(row));
    end
    qa.expectedRuns = 80;
    qa.completedRuns = 80;
    qa.northRuns = nnz(index.Axis=="North");
    qa.eastRuns = nnz(index.Axis=="East");
    qa.identicalInheritedCompletedRows = identicalInheritedRows;
    qa.checkpointFileCount = numel(checkpointFiles);
    qa.totalScans = height(allScans);
    qa.maxInitialPositionErrorM = max([runQa.initialPositionErrorM]);
    qa.nativePositionSamplesChecked = sum([runQa.nativePositionSampleCount]);
    qa.rawCloudScansChecked = sum([runQa.scanCount]);
    qa.nativeLidarAlwaysEnabled = true;
    qa.manifestTelemetryEpisodeIdsMatch = true;
    qa.scanCadence10HzVerified = true;
    qa.goalAndControllerReferenceSeparated = true;
    qa.attitudeAndBodyAngularVelocityPresent = true;
    qa.rawPointCloudsRetainedAndRangesRecomputed = true;
    qa.outcomeLabelsIndependentlyRecomputed = true;
    qa.allowedUnavailableValues = [ ...
        "episode.action.previous first row: NaN with previousAvailable=false"; ...
        "raw LiDAR XYZ: absent returns may be nonfinite; validity masks verified"; ...
        "scans.csv NearestValidReturnM: NaN only for scans without valid returns"];
    qa.runs = runQa;
    attemptFiles=dir(fullfile(batchPath,"attempts","*.json"));
    failedExportAttempts=0; failedSimulationAttempts=0;
    for attemptIndex=1:numel(attemptFiles)
        attempt=jsondecode(fileread(fullfile(attemptFiles(attemptIndex).folder,attemptFiles(attemptIndex).name)));
        if string(attempt.status)=="instrumentation-failed"
            if ismember(string(attempt.stage),["build-episode","save-raw"])
                failedExportAttempts=failedExportAttempts+1;
            else
                failedSimulationAttempts=failedSimulationAttempts+1;
            end
        end
    end
    qa.failedExportAttempts=failedExportAttempts;
    qa.failedSimulationAttempts=failedSimulationAttempts;
    qa.exportRecoveryRecords=numel(dir(fullfile(batchPath,"recoveries","*.json")));
    qa.allDataChecksPassed = true;
    summary = struct("schemaVersion","lidar-axis-batch-summary-v1", ...
        "batchId",string(metadata.batchId),"updatedAtUtc",utcNow(), ...
        "plannedRuns",80,"completedRuns",80, ...
        "northRuns",qa.northRuns,"eastRuns",qa.eastRuns, ...
        "instrumentationFailures",0,"missionSuccesses",nnz(index.MissionSuccess), ...
        "failedExportAttempts",failedExportAttempts, ...
        "failedSimulationAttempts",failedSimulationAttempts, ...
        "exportRecoveryRecords",qa.exportRecoveryRecords, ...
        "sourceAmendmentCount",qa.sourceAmendmentCount, ...
        "missionFailures",nnz(~index.MissionSuccess), ...
        "collisions",nnz(index.CollisionOccurred), ...
        "safetyPassedRuns",nnz(index.SafetyChecksPassed), ...
        "safetyFailedRuns",nnz(~index.SafetyChecksPassed), ...
        "goalReachedAtAnyTimeRuns",nnz([runQa.goalReachedAtAnyTime]), ...
        "goalReachedAtTerminationRuns",nnz([runQa.goalReachedAtTermination]), ...
        "timeLimitRuns",nnz([runQa.timedOut]), ...
        "earlyStopBeforeGoalRuns",nnz(string(index.TerminationReason)=="early-stop-before-goal"), ...
        "altitudeFailedRuns",nnz(~[runQa.altitudeWithinLimits]), ...
        "nearCollisionRuns",nnz([runQa.nearCollisionOccurred]), ...
        "totalScans",height(allScans), ...
        "minimumScanCount",min(index.ScanCount),"maximumScanCount",max(index.ScanCount), ...
        "minimumDurationS",min(index.DurationS),"maximumDurationS",max(index.DurationS), ...
        "meanDurationS",mean(index.DurationS), ...
        "maxInitialPositionErrorM",qa.maxInitialPositionErrorM, ...
        "minimumSurfaceClearanceM",min(index.MinimumSurfaceClearanceM), ...
        "maximumFinalWaypointErrorM",max(index.FinalWaypointErrorM), ...
        "allDataChecksPassed",true, ...
        "collisionDetectionMethod",qa.collisionDetectionMethod);
    atomicTable(fullfile(batchPath,"all_scans.csv"),allScans);
    atomicCheckpoint(batchPath,index);
    atomicJson(fullfile(batchPath,"summary.json"),summary);
    atomicJson(fullfile(batchPath,"dataset_qa.json"),qa);
    fprintf("BATCH_VERIFIED 80/80 totalScans=%d successes=%d collisions=%d\n", ...
        summary.totalScans,summary.missionSuccesses,summary.collisions);
catch failure
    qa.allDataChecksPassed = false;
    qa.failureIdentifier = string(failure.identifier);
    qa.failureMessage = string(failure.message);
    qa.checkedAtUtc = utcNow();
    if isfolder(batchPath)
        atomicJson(fullfile(batchPath,"dataset_qa.json"),qa);
    end
    rethrow(failure);
end
end

function validatePlan(plan)
require(istable(plan) && height(plan)==80,"Frozen plan must contain 80 runs.");
require(isequal(plan.RunIndex,(1:80)'),"Plan RunIndex must be 1:80 in order.");
require(nnz(plan.Axis=="North")==40 && nnz(plan.Axis=="East")==40, ...
    "Plan must contain exactly 40 starts on each axis.");
position = [plan.PositionNorthM plan.PositionEastM plan.PositionDownM];
require(all(isfinite(position),"all") && all(position(:,3)==-7), ...
    "Plan positions must be finite and use Down=-7.");
require(all(plan.PositionEastM(plan.Axis=="North")==0) && ...
    all(plan.PositionNorthM(plan.Axis=="East")==0),"Starts must lie on their named NED axes.");
require(size(unique(position,"rows"),1)==80,"Plan contains duplicate starting positions.");
require(all(plan.PositionNorthM(plan.Axis=="North")>0 & ...
    plan.PositionNorthM(plan.Axis=="North")<30) && ...
    all(plan.PositionEastM(plan.Axis=="East")>0 & ...
    plan.PositionEastM(plan.Axis=="East")<35),"Starts exceed current mission axis spans.");
end

function [scan,qa] = auditRun(row,plan,metadata)
context = "RunIndex "+row.RunIndex+" ("+string(row.RunId)+"): ";
paths = [string(row.RawTelemetryPath),string(row.EpisodePath),string(row.ScanTablePath)];
require(all(isfile(paths)),context+"a completed artifact is missing.");
manifestPath = fullfile(fileparts(row.RawTelemetryPath),"manifest.json");
require(isfile(manifestPath),context+"manifest.json is missing.");
manifest = jsondecode(fileread(manifestPath));
raw = load(row.RawTelemetryPath,"telemetry");
processed = load(row.EpisodePath,"episode");
require(isfield(raw,"telemetry") && isfield(processed,"episode"),context+"MAT artifact payload is missing.");
telemetry = raw.telemetry; episode = processed.episode;
authorizedProvenance=false;
for snapshotIndex=1:numel(metadata.authorizedSourceSnapshots)
    expected=jsondecode(jsonencode(metadata.authorizedSourceSnapshots{snapshotIndex}));
    authorizedProvenance=authorizedProvenance || isequaln(manifest.provenance,expected);
end
require(authorizedProvenance,context+"manifest provenance is absent from the source amendment chain.");
id = string(row.RunId);
require(string(manifest.runId)==id && string(telemetry.runId)==id && ...
    string(episode.runId)==id,context+"manifest/raw/episode RunIds differ.");
require(string(manifest.experiment.batchId)==string(metadata.batchId) && ...
    manifest.experiment.runIndex==row.RunIndex && ...
    string(manifest.experiment.axis)==string(plan.Axis) && ...
    manifest.experiment.axisIndex==plan.AxisIndex && ...
    manifest.experiment.randomSeed==plan.SimulationSeed,context+"manifest experiment identity differs from plan.");
require(string(telemetry.experiment.batchId)==string(metadata.batchId) && ...
    telemetry.experiment.runIndex==row.RunIndex && ...
    string(telemetry.experiment.axis)==string(plan.Axis),context+"raw experiment identity differs.");
start = [plan.PositionNorthM plan.PositionEastM plan.PositionDownM];
cfg = manifest.configuration;
cfg.mission.initialPositionNed = double(cfg.mission.initialPositionNed(:)');
assertClose(double(cfg.mission.initialPositionNed(:)'),start,1e-10,context+"configured spawn");
assertClose(double(cfg.mission.waypointsNed(1,:)),start,1e-10,context+"first waypoint");
assertClose(double(cfg.mission.waypointsNed(end,:)),[30 35 -7],1e-10,context+"final waypoint");
require(logical(cfg.sensors.lidar.enabled),context+"manifest disables LiDAR.");
assertClose(double(manifest.static.initial_position_ned_m(:)'),start,1e-10, ...
    context+"static configured spawn");
assertClose(double(manifest.static.obstacle_centers_ned_m), ...
    double(metadata.obstacleCentersNedM),1e-10,context+"NED obstacle geometry");
assertClose(double(manifest.static.obstacle_centers_enu_m), ...
    double(metadata.obstacleCentersEnuM),1e-10,context+"ENU obstacle geometry");
require(manifest.static.obstacle_width_m==metadata.obstacleWidthM && ...
    manifest.static.obstacle_height_m==metadata.obstacleHeightM && ...
    string(manifest.static.obstacle_mesh_reference_frame)=="ENU", ...
    context+"manifest obstacle geometry or frame differs.");
require(string(telemetry.coordinateFrame)=="NED" && string(episode.coordinateFrame)=="NED", ...
    context+"coordinate frame is not NED.");
signalNames = fieldnames(telemetry.signals);
for nameIndex = 1:numel(signalNames)
    name = signalNames{nameIndex}; signal = telemetry.signals.(name);
    require(isstruct(signal) && isfield(signal,"time_s") && isfield(signal,"values"), ...
        context+"noncanonical raw signal "+name);
    time = double(signal.time_s(:)); values = signal.values;
    require(~isempty(time) && isreal(time) && all(isfinite(time)) && ...
        all(diff(time)>=0) && time(1)>=0 && isreal(values) && ...
        ismatrix(values) && size(values,1)==numel(time) && ...
        all(isfinite(double(values)),"all"),context+"invalid native signal "+name);
end
requiredState = ["attitude_ned_rpy_rad","angular_velocity_body_radps", ...
    "position_ned_m","velocity_ned_mps","desired_position_ned_m"];
for name = requiredState
    require(isfield(telemetry.signals,name) && size(telemetry.signals.(name).values,2)==3, ...
        context+"missing or invalid native state/reference "+name);
end
require(all(telemetry.signals.lidar_enabled.values==1,"all"), ...
    context+"native LiDAR enable signal contains an outage.");
time = double(episode.time_s(:)); count = numel(time);
require(count>=2 && all(isfinite(time)) && all(diff(time)>0) && ...
    max(abs(diff(time)-0.1))<1e-6,context+"scan times are not strictly increasing at 10 Hz.");
require(abs(time(1))<1e-10 && ...
    isequal(double(episode.metadata.gridSize(:)'),[15 716]) && ...
    episode.metadata.maximumRangeM==7 && episode.metadata.observationDimension==10740, ...
    context+"LiDAR timeline origin, grid or maximum range differs from the current scenario.");
require(count==row.ScanCount && isequal(double(episode.sampleIndex(:)),(1:count)'), ...
    context+"scan count or sample indices differ from index.");
require(isequal(time,double(telemetry.signals.nominal_observation.time_s(:))) && ...
    isequal(time,double(telemetry.signals.nominal_lidar_valid_return_mask.time_s(:))), ...
    context+"raw and processed scan timelines differ.");
require(isequal(size(episode.lidar.ranges_m),[count 10740]) && ...
    isequal(size(episode.lidar.validReturnMask),[count 10740]) && ...
    isequal(size(episode.lidar.availabilityMask),[count 10740]) && ...
    isequal(size(episode.lidar.missingMask),[count 10740]),context+"episode LiDAR array shape differs from [N,10740].");
ranges = double(episode.lidar.ranges_m);
valid = logical(episode.lidar.validReturnMask);
require(all(isfinite(ranges),"all") && all(ranges>=0 & ranges<=7,"all") && ...
    all(ranges(valid)>0) && all(ranges(~valid)==7),context+"invalid range or no-return encoding.");
require(all(episode.lidar.availabilityMask,"all") && ...
    ~any(episode.lidar.missingMask,"all") && all(episode.lidar.enabled), ...
    context+"processed episode contradicts always-on healthy LiDAR.");
assertClose(double(telemetry.signals.nominal_observation.values),ranges,1e-10,context+"raw observations");
assertClose(double(telemetry.signals.nominal_lidar_ranges_m.values),ranges,1e-10,context+"raw ranges");
require(isequal(logical(telemetry.signals.nominal_lidar_valid_return_mask.values),valid), ...
    context+"raw and processed validity masks differ.");
require(isfield(episode,"reference") && isfield(episode.reference,"desiredPositionNed_m"), ...
    context+"controller reference is missing.");
require(isfield(episode.state,"attitudeNedRpy_rad") && ...
    isfield(episode.state,"angularVelocityBody_radps"),context+"processed attitude or body angular velocity is missing.");
assertClose(double(episode.state.positionNed_m),sampleNative( ...
    telemetry.signals.position_ned_m,time,"linear"),1e-9,context+"scan-aligned native position");
assertClose(double(episode.state.velocityNed_mps),sampleNative( ...
    telemetry.signals.velocity_ned_mps,time,"linear"),1e-9,context+"scan-aligned native velocity");
assertClose(double(episode.state.attitudeNedRpy_rad),sampleNative( ...
    telemetry.signals.attitude_ned_rpy_rad,time,"angular"),1e-9,context+"scan-aligned native attitude");
assertClose(double(episode.state.angularVelocityBody_radps),sampleNative( ...
    telemetry.signals.angular_velocity_body_radps,time,"linear"),1e-9,context+"scan-aligned native angular velocity");
assertClose(double(episode.reference.desiredPositionNed_m),sampleNative( ...
    telemetry.signals.desired_position_ned_m,time,"previous"),1e-9,context+"scan-aligned native controller reference");
actionNames = ["command_roll_rad","command_pitch_rad", ...
    "command_yaw_rate_radps","command_thrust_n"];
require(isequal(size(episode.action.current),[count 4]),context+"current action shape differs from [N,4].");
for actionIndex = 1:4
    assertClose(double(episode.action.current(:,actionIndex)),sampleNative( ...
        telemetry.signals.(actionNames(actionIndex)),time,"previous"), ...
        1e-9,context+"scan-aligned native action "+actionNames(actionIndex));
end
assertClose(double(episode.obstacleAvoidanceStatus),sampleNative( ...
    telemetry.signals.obstacle_avoidance_status,time,"previous"),0,context+"scan-aligned native avoidance status");
assertClose(double(episode.goal.positionNed_m),repmat([30 35 -7],count,1), ...
    1e-10,context+"true final mission goal");
assertClose(double(telemetry.mission.finalGoalPositionNed_m(:)'),[30 35 -7], ...
    1e-10,context+"raw true mission goal");
checkFiniteEpisode(episode,"episode",context);
require(isequal(size(episode.action.previous),[count 4]) && ...
    all(isnan(episode.action.previous(1,:))) && ...
    isequal(logical(episode.action.previousAvailable(:)),[false;true(count-1,1)]), ...
    context+"previous-action availability is incorrect.");
assertClose(double(episode.action.previous(2:end,:)),double(episode.action.current(1:end-1,:)), ...
    1e-10,context+"previous scan actions");
require(isfield(telemetry,"rawLidar") && isfield(telemetry.rawLidar,"pointsXyz_m") && ...
    isequal(size(telemetry.rawLidar.pointsXyz_m),[15 716 3 count]) && ...
    isequal(double(telemetry.rawLidar.time_s(:)),time),context+"organized raw XYZ point clouds are missing or misaligned.");
nearest = nan(count,1);
for scanIndex = 1:count
    xyz = reshape(double(telemetry.rawLidar.pointsXyz_m(:,:,:,scanIndex)),10740,3);
    measuredRange = sqrt(sum(xyz.^2,2));
    measuredValid = all(isfinite(xyz),2) & isfinite(measuredRange) & ...
        measuredRange>0 & measuredRange<=7+7e-6;
    require(isequal(measuredValid,valid(scanIndex,:)'),context+"raw XYZ validity differs at scan "+scanIndex+".");
    measuredRange(measuredValid) = min(measuredRange(measuredValid),7);
    measuredRange(~measuredValid) = 7;
    assertClose(measuredRange,ranges(scanIndex,:)',1e-10, ...
        context+"XYZ-derived range at scan "+scanIndex);
    if any(measuredValid), nearest(scanIndex)=min(measuredRange(measuredValid)); end
end
metrics = ares.data.evaluateAxisRun(telemetry,cfg, ...
    metadata.obstacleCentersNedM,metadata.obstacleWidthM,metadata.obstacleHeightM);
require(metrics.telemetryValid && metrics.initialPositionMatchesPlan && ...
    metrics.initialPositionErrorM<=1e-4,context+"actual native starting position differs from plan.");
spawnTelemetry.signals.position_ned_m = struct("time_s",[0;1],"values",[start;start]);
spawnMetrics = ares.data.evaluateAxisRun(spawnTelemetry,cfg, ...
    metadata.obstacleCentersNedM,metadata.obstacleWidthM,metadata.obstacleHeightM);
require(spawnMetrics.minimumObstacleClearanceM>=cfg.safety.minimumSurfaceClearanceM, ...
    context+"planned starting position violates the configured surface-clearance requirement.");
logicalMetrics = ["telemetryValid","collisionOccurred","nearCollisionOccurred","altitudeWithinLimits", ...
    "goalReachedAtAnyTime","goalReachedAtTermination","reachedTimeLimit", ...
    "timedOut","safetyChecksPassed","missionSuccess","initialPositionMatchesPlan"];
numericMetrics = ["positionSampleCount","finalWaypointErrorM","minimumAltitudeM","maximumAltitudeM", ...
    "minimumObstacleCenterDistanceM","minimumObstacleClearanceM", ...
    "requiredObstacleClearanceM","requiredObstacleCenterDistanceM", ...
    "initialPositionErrorM","durationS","finalTimeS","totalPathLengthM"];
for name = logicalMetrics
    require(logical(manifest.metrics.(name))==metrics.(name) && ...
        logical(telemetry.metrics.(name))==metrics.(name),context+"saved metric differs: "+name);
end
for name = numericMetrics
    assertClose(double(manifest.metrics.(name)),metrics.(name),1e-8,context+"manifest metric "+name);
    assertClose(double(telemetry.metrics.(name)),metrics.(name),1e-8,context+"raw metric "+name);
end
require(string(manifest.metrics.terminationReason)==metrics.terminationReason && ...
    string(telemetry.metrics.terminationReason)==metrics.terminationReason && ...
    string(row.TerminationReason)==metrics.terminationReason,context+"termination reason differs.");
require(logical(row.MissionSuccess)==metrics.missionSuccess && ...
    logical(row.CollisionOccurred)==metrics.collisionOccurred && ...
    logical(row.SafetyChecksPassed)==metrics.safetyChecksPassed && ...
    logical(manifest.outcome.missionSuccess)==metrics.missionSuccess && ...
    logical(manifest.outcome.collisionOccurred)==metrics.collisionOccurred && ...
    logical(manifest.outcome.safetyChecksPassed)==metrics.safetyChecksPassed && ...
    logical(telemetry.outcome.missionSuccess)==metrics.missionSuccess && ...
    logical(telemetry.outcome.collisionOccurred)==metrics.collisionOccurred && ...
    logical(telemetry.outcome.safetyChecksPassed)==metrics.safetyChecksPassed, ...
    context+"outcome labels differ from native trajectory.");
assertClose(double(row.DurationS),metrics.durationS,1e-8,context+"index duration");
assertClose(double(row.FinalWaypointErrorM),metrics.finalWaypointErrorM,1e-8,context+"index goal error");
assertClose(double(row.MinimumSurfaceClearanceM),metrics.minimumObstacleClearanceM,1e-8,context+"index surface clearance");
fraction = nnz(valid)/numel(valid);
assertClose(double(row.ValidReturnFraction),fraction,1e-10,context+"index valid return fraction");
assertClose(double(episode.metadata.validReturnFraction),fraction,1e-10,context+"episode valid return fraction");
scan = readtable(row.ScanTablePath,"TextType","string");
require(height(scan)==count && all(string(scan.RunId)==id) && ...
    all(string(scan.Axis)==string(plan.Axis)) && ...
    isequal(double(scan.SampleIndex),(1:count)'),context+"scan CSV identities/count/indices differ.");
assertClose(double(scan.TimeS),time,1e-10,context+"scan CSV time");
columns = ["PositionNorthM","PositionEastM","PositionDownM", ...
    "VelocityNorthMps","VelocityEastMps","VelocityDownMps", ...
    "RollRad","PitchRad","YawRad", ...
    "BodyRollRateRadps","BodyPitchRateRadps","BodyYawRateRadps", ...
    "GoalNorthM","GoalEastM","GoalDownM", ...
    "DesiredReferenceNorthM","DesiredReferenceEastM","DesiredReferenceDownM", ...
    "CommandRollRad","CommandPitchRad","CommandYawRateRadps","CommandThrustN"];
expected = [episode.state.positionNed_m,episode.state.velocityNed_mps, ...
    episode.state.attitudeNedRpy_rad,episode.state.angularVelocityBody_radps, ...
    episode.goal.positionNed_m,episode.reference.desiredPositionNed_m,episode.action.current];
assertClose(double(scan{:,cellstr(columns)}),double(expected),1e-8,context+"scan CSV state/goal/reference/action");
assertClose(double(scan.ValidReturnFraction),sum(valid,2)/10740,1e-10,context+"scan CSV return fractions");
require(isequal(isnan(double(scan.NearestValidReturnM)),isnan(nearest)), ...
    context+"scan CSV nearest-return availability differs.");
assertClose(double(scan.NearestValidReturnM(~isnan(nearest))),nearest(~isnan(nearest)), ...
    1e-8,context+"scan CSV nearest return");
assertClose(double(scan.DistanceToFinalGoalM),vecnorm(episode.state.positionNed_m-[30 35 -7],2,2), ...
    1e-8,context+"scan CSV final-goal distances");
assertClose(double(scan.ObstacleAvoidanceStatus),double(episode.obstacleAvoidanceStatus), ...
    0,context+"scan CSV avoidance status");
require(all(scan.LidarEnabled==1) && ...
    isequal(logical(scan.PreviousActionAvailable),logical(episode.action.previousAvailable)), ...
    context+"scan CSV availability labels differ.");
for columnIndex = 1:width(scan)
    name = string(scan.Properties.VariableNames{columnIndex}); values = scan{:,columnIndex};
    if isnumeric(values) || islogical(values)
        if name=="NearestValidReturnM"
            require(all(isfinite(values(~isnan(nearest)))),context+"unexpected nonfinite nearest return.");
        else
            require(all(isfinite(double(values)),"all"),context+"nonfinite scan CSV field "+name);
        end
    end
end
qa = struct("runIndex",row.RunIndex,"runId",id,"axis",string(plan.Axis), ...
    "scanCount",count,"nativePositionSampleCount",metrics.positionSampleCount, ...
    "initialPositionErrorM",metrics.initialPositionErrorM, ...
    "durationS",metrics.durationS,"goalReachedAtAnyTime",metrics.goalReachedAtAnyTime, ...
    "goalReachedAtTermination",metrics.goalReachedAtTermination, ...
