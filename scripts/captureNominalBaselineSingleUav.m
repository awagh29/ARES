proj = currentProject;
projectRoot = string(proj.RootFolder);

modelName = "ares_single_uav_top";
experimentName = "nominal-baseline-single-uav";

contract = ares.data.defaultDataContract();

experimentCfg = ares.config.defaultSingleUav();
experimentCfg.sensors.lidar.enabled = true;

baselineSeed = 42;
rng(baselineSeed, "twister");

manifest = ares.data.createRunManifest( ...
    projectRoot, ...
    modelName, ...
    experimentName, ...
    experimentCfg);

% Associate this episode with the new data contract.
manifest.dataContractSchemaVersion = ...
    contract.schemaVersion;

manifest.dataContractSystemName = ...
    contract.systemName;

manifest.groundTruth.condition = "nominal";
manifest.groundTruth.faultType = "none";
manifest.groundTruth.faultActive = false;
manifest.groundTruth.faultStartTime_s = NaN;
manifest.groundTruth.faultEndTime_s = NaN;
manifest.groundTruth.expectedMissionOutcome = ...
    "reach-goal-without-collision";

manifest.experiment.randomSeed = baselineSeed;
manifest.experiment.scenarioType = ...
    "single-uav-nominal-baseline";

% Consumed by initializeSingleUav.m.
SingleUavConfigOverride = experimentCfg;

fprintf("\nStarting nominal baseline episode...\n");

run(fullfile( ...
    projectRoot, ...
    "scripts", ...
    "runSingleUav.m"));

%% Simulation validation

assert( ...
    exist("simOut", "var") == 1 && ...
    isa(simOut, "Simulink.SimulationOutput"), ...
    "ARES:MissingSimulationOutput", ...
    "The nominal run did not produce simOut.");

assert( ...
    LidarEnabled, ...
    "ARES:UnexpectedLidarState", ...
    "LiDAR was disabled during the nominal episode.");

simulationTime = double(simOut.tout(:));

assert( ...
    numel(simulationTime) >= 2, ...
    "ARES:InvalidTimeline", ...
    "The simulation timeline contains fewer than two samples.");

assert( ...
    all(isfinite(simulationTime)), ...
    "ARES:InvalidTimeline", ...
    "The simulation timeline contains nonfinite values.");

assert( ...
    all(diff(simulationTime) >= 0), ...
    "ARES:InvalidTimeline", ...
    "Simulation timestamps are not monotonic.");

manifest.groundTruth.faultEndTime_s = NaN;

manifest.outcome.safetyChecksPassed = true;
manifest.outcome.failureIdentifier = "";
manifest.outcome.failureMessage = "";

manifest.metrics.finalWaypointErrorM = ...
    finalWaypointErrorM;

manifest.metrics.minimumAltitudeM = ...
    minimumAltitudeM;

manifest.metrics.maximumAltitudeM = ...
    maximumAltitudeM;

manifest.metrics.minimumObstacleClearanceM = ...
    minimumObstacleClearanceM;

manifest.metrics.requiredObstacleClearanceM = ...
    requiredObstacleClearanceM;

lidarGridSize = [15 716];
lidarObservationDimension = prod(lidarGridSize);

[elevationIndex, azimuthIndex] = ind2sub( ...
    lidarGridSize, (1:lidarObservationDimension)');

lidarChannelNames = compose( "lidar_e%02d_a%03d_range_m", ...
    elevationIndex, azimuthIndex);

manifest.static.maximum_sensor_range_m = double(MaxRange);

manifest.static.nominal_observation_schema = ...
    "organized-lidar-range-vector-v1";

manifest.static.nominal_observation_dimension = lidarObservationDimension;

manifest.static.nominal_lidar_grid_size = lidarGridSize;

manifest.static.observation_channel_names = lidarChannelNames';

manifest.static.reconstructable_channel_indices = ...
    1:lidarObservationDimension;

manifest.static.observation_channel_order = ...
    "elevation-index-fastest-then-azimuth-index";

manifest.static.invalid_lidar_return_encoding = ...
    "maximum-range-with-validity-mask";

manifest.static.maximum_sensor_range_m = double(MaxRange);

manifest.static.nominal_observation_schema = ...
    "organized-lidar-range-vector-v1";

manifest.static.nominal_observation_dimension = lidarObservationDimension;

manifest.static.observation_channel_order = ...
    "elevation-index-fastest-then-azimuth-index";

manifest.static.lidar_grid_size = lidarGridSize;

telemetry = ares.data.extractRawTelemetry(simOut, manifest);

assert( ...
    ~isempty(telemetry), ...
    "ARES:EmptyTelemetry", ...
    "Telemetry extraction returned an empty value.");

%% Save artifacts

manifestPath = ares.data.saveRuntimeManifest( ...
    projectRoot, ...
    manifest);

telemetryPath = ares.data.saveRawTelemetry( ...
    projectRoot, ...
    telemetry);

assert( ...
    isfile(manifestPath), ...
    "ARES:ManifestNotSaved", ...
    "The runtime manifest was not saved.");

assert( ...
    isfile(telemetryPath), ...
    "ARES:TelemetryNotSaved", ...
    "The telemetry artifact was not saved.");

manifestFileInfo = dir(manifestPath);
telemetryFileInfo = dir(telemetryPath);

assert( ...
    manifestFileInfo.bytes > 0, ...
    "ARES:EmptyManifestFile", ...
    "The saved manifest file is empty.");

assert( ...
    telemetryFileInfo.bytes > 0, ...
    "ARES:EmptyTelemetryFile", ...
    "The saved telemetry file is empty.");

%% Inspect current telemetry shape

fprintf("\nTelemetry MATLAB type: %s\n", ...
    class(telemetry));

if istable(telemetry) || istimetable(telemetry)

    emittedFields = string( ...
        telemetry.Properties.VariableNames);

    fprintf("Telemetry rows: %d\n", ...
        height(telemetry));

elseif isstruct(telemetry)

    emittedFields = string(fieldnames(telemetry));

    fprintf("Telemetry top-level fields: %d\n", ...
        numel(emittedFields));

else
    emittedFields = strings(0, 1);
end

disp("Currently emitted telemetry fields:");
disp(emittedFields);

%% New-contract coverage report

requiredDynamicFields = ...
    string(contract.dynamicFields(:));

implementedDynamicFields = intersect( ...
    requiredDynamicFields, ...
    emittedFields, ...
    "stable");

missingDynamicFields = setdiff( ...
    requiredDynamicFields, ...
    emittedFields, ...
    "stable");

coveragePercent = ...
    100 * numel(implementedDynamicFields) / ...
    numel(requiredDynamicFields);

coverageReport = table( ...
    numel(requiredDynamicFields), ...
    numel(implementedDynamicFields), ...
    numel(missingDynamicFields), ...
    coveragePercent, ...
    VariableNames=[ ...
        "RequiredDynamicFields", ...
        "ImplementedDynamicFields", ...
        "MissingDynamicFields", ...
        "CoveragePercent"]);

disp("New data-contract coverage:");
disp(coverageReport);

disp("Missing dynamic fields:");
disp(missingDynamicFields);

%% Final summary

fprintf("\nPASS: Nominal telemetry pipeline completed.\n");
fprintf("Schema version: %s\n", ...
    contract.schemaVersion);
fprintf("Simulation samples: %d\n", ...
    numel(simulationTime));
fprintf("Final waypoint error: %.3f m\n", ...
    finalWaypointErrorM);
fprintf("Minimum clearance: %.3f m\n", ...
    minimumObstacleClearanceM);
fprintf("Manifest: %s\n", ...
    manifestPath);
fprintf("Telemetry: %s\n", ...
    telemetryPath);