%% Local schedule generator

function [schedule, intervals] = createRandomLidarSchedule( ...
            simulationStopTime, faultCfg)

    outageCount = faultCfg.numberOfOutages;

    assert(outageCount >= 1, ...
        "ARES:InvalidOutageCount", ...
        "At least one LiDAR outage is required.");

    faultWindowEndTime = min( ...
        double(simulationStopTime), ...
        double(faultCfg.faultWindowEndTime_s));

    minimumRequiredTime = ...
        faultCfg.initialHealthyTime_s ...
        + outageCount ...
            * faultCfg.minimumOutageDuration_s ...
        + max(outageCount - 1, 0) ...
            * faultCfg.minimumRecoveryDuration_s ...
        + faultCfg.finalHealthyTime_s;

    assert( ...
        faultWindowEndTime >= minimumRequiredTime, ...
        "ARES:InsufficientFaultScheduleTime", ...
        ["The %.2f-second fault window is too short. " + ...
         "At least %.2f seconds are required."], ...
        faultWindowEndTime, ...
        minimumRequiredTime);

    assert( ...
        faultCfg.maximumOutageDuration_s >= ...
            faultCfg.minimumOutageDuration_s, ...
        "ARES:InvalidOutageDurationRange", ...
        "Maximum outage duration must be at least the minimum duration.");

    randomStream = RandStream( ...
        "mt19937ar", ...
        "Seed", ...
        faultCfg.randomSeed);

    intervals = zeros( ...
        outageCount, ...
        2);

    earliestStartTime = ...
        faultCfg.initialHealthyTime_s;

    for outageIndex = 1:outageCount
        remainingOutages = ...
            outageCount - outageIndex;

        remainingMinimumTime = ...
            faultCfg.finalHealthyTime_s ...
            + remainingOutages ...
                * faultCfg.minimumOutageDuration_s ...
            + remainingOutages ...
                * faultCfg.minimumRecoveryDuration_s;

        latestStartTime = ...
            faultWindowEndTime ...
            - faultCfg.minimumOutageDuration_s ...
            - remainingMinimumTime;

        assert( ...
            latestStartTime >= earliestStartTime, ...
            "ARES:InvalidFaultScheduleWindow", ...
            ["No valid start-time window remains " + ...
             "for outage %d."], ...
            outageIndex);

        availableStartSlack = ...
            latestStartTime ...
            - earliestStartTime;

        startTime = ...
            earliestStartTime ...
            + rand(randomStream) ...
                * availableStartSlack;

        maximumAllowedDuration = min( ...
            faultCfg.maximumOutageDuration_s, ...
            faultWindowEndTime ...
                - startTime ...
                - remainingMinimumTime);

        assert( ...
            maximumAllowedDuration >= ...
                faultCfg.minimumOutageDuration_s, ...
            "ARES:InvalidFaultDurationWindow", ...
            ["No valid duration remains " + ...
             "for outage %d."], ...
            outageIndex);

        availableDurationSlack = ...
            maximumAllowedDuration ...
            - faultCfg.minimumOutageDuration_s;

        outageDuration = ...
            faultCfg.minimumOutageDuration_s ...
            + rand(randomStream) ...
                * availableDurationSlack;

        endTime = ...
            startTime + outageDuration;

        intervals(outageIndex, :) = ...
            [startTime, endTime];

        earliestStartTime = ...
            endTime ...
            + faultCfg.minimumRecoveryDuration_s;
    end

    assert( ...
        intervals(end, 2) + ...
            faultCfg.finalHealthyTime_s <= ...
            faultWindowEndTime + 1e-9, ...
        "ARES:MissingFinalHealthyWindow", ...
        "The schedule does not retain the required final healthy period.");

    transitionTimes = [
        0
        reshape(intervals.', [], 1)
        simulationStopTime
        ];

    % Starts enabled, alternates off/on, and remains enabled after the
    % final recovery until the configured simulation stop time.
    availabilityValues = [
        1
        repmat([0; 1], outageCount, 1)
        1
        ];

    assert( ...
        numel(transitionTimes) == ...
            numel(availabilityValues), ...
        "ARES:InvalidFaultSchedule", ...
        "Schedule times and values have different lengths.");

    assert( ...
        all(diff(transitionTimes) > 0), ...
        "ARES:NonIncreasingFaultSchedule", ...
        "LiDAR schedule timestamps must be strictly increasing.");

    schedule = timeseries( ...
        availabilityValues, ...
        transitionTimes);

    schedule = setinterpmethod( ...
        schedule, ...
        "zoh");

    schedule.Name = ...
        "lidar_enabled";
end

function signal = createTelemetrySignal( ...
        time_s, values, signalName, unitName, componentNames)

    time_s = double(time_s(:));

    if isvector(values)
        values = values(:);
    end

    assert( ...
        size(values, 1) == numel(time_s), ...
        "ARES:TelemetrySignalLengthMismatch", ...
        "Signal %s has %d rows but %d timestamps.", ...
        signalName, ...
        size(values, 1), ...
        numel(time_s));

    expectedWidth = ...
        size(values, 2);

    signalTimeseries = timeseries( ...
        values, ...
        time_s);

    signal = ares.data.timeseriesToSignal( ...
        signalTimeseries, ...
        expectedWidth);

    signal.name = signalName;
    signal.unit = unitName;
    signal.components = componentNames;
end

function values = getTelemetrySignalValues(signal)

    if isa(signal, "timeseries")
        values = signal.Data;
        return;
    end

    assert( ...
        isstruct(signal), ...
        "ARES:UnsupportedTelemetrySignal", ...
        "Telemetry signals must be structs or timeseries objects.");

    candidateFields = [
        "values"
        "data"
        "samples"
        "value"
        ];

    for fieldIndex = 1:numel(candidateFields)
        fieldName = candidateFields(fieldIndex);

        if isfield(signal, fieldName)
            values = signal.(fieldName);
            return;
        end
    end

    availableFields = ...
        strjoin(string(fieldnames(signal)), ", ");

    error( ...
        "ARES:MissingTelemetryValues", ...
        "Could not locate signal values. Available fields: %s", ...
        availableFields);
end

function values = orientSamplesByRow( ...
        values, expectedSampleCount, signalName)

    values = squeeze(values);

    if size(values, 1) == expectedSampleCount
        return;
    end

    if size(values, 2) == expectedSampleCount
        values = values.';
        return;
    end

    error( ...
        "ARES:TelemetryOrientationMismatch", ...
        "Signal %s cannot be aligned to %d samples.", ...
        signalName, ...
        expectedSampleCount);
end

function elapsedTime_s = ...
        calculateTimeSinceLastValidScan( ...
            time_s, validScanMask)

    time_s = double(time_s(:));
    validScanMask = logical(validScanMask(:));

    elapsedTime_s = zeros(size(time_s));
    lastValidTime_s = NaN;

    for sampleIndex = 1:numel(time_s)
        if validScanMask(sampleIndex)
            lastValidTime_s = time_s(sampleIndex);
            elapsedTime_s(sampleIndex) = 0;
        elseif isnan(lastValidTime_s)
            elapsedTime_s(sampleIndex) = Inf;
        else
            elapsedTime_s(sampleIndex) = ...
                time_s(sampleIndex) ...
                - lastValidTime_s;
        end
    end
end