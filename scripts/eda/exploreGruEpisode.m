function eda = exploreGruEpisode( ...
        gruEpisodePath, outputFolder)

    arguments
        gruEpisodePath (1,1) string
        outputFolder (1,1) string = ""
    end

    loadedData = load(gruEpisodePath);

    assert(isfield(loadedData, "gruEpisode"), ...
        "ARES:MissingGruEpisode", ...
        "The MAT file does not contain gruEpisode.");

    episode = loadedData.gruEpisode;

    if strlength(outputFolder) == 0
        outputFolder = fullfile( ...
            fileparts(gruEpisodePath), ...
            "eda");
    end

    if ~isfolder(outputFolder)
        mkdir(outputFolder);
    end

    %% Extract episode data

    time_s = double(episode.time_s(:));

    target = double( ...
        episode.targets.nominalObservation);

    degraded = double( ...
        episode.inputs.degradedObservation);

    missingMask = logical( ...
        episode.targets.lossMask);

    availabilityMask = logical( ...
        episode.inputs.availabilityMask);

    validReturnMask = logical( ...
        episode.targets.nominalValidReturnMask);

    degradedValidReturnMask = logical( ...
        episode.inputs.degradedValidReturnMask);

    failureActive = logical( ...
        episode.labels.failureActive(:));

    gridSize = double( ...
        episode.metadata.gridSize);

    maximumRangeM = double( ...
        episode.metadata.maximumRangeM);

    [numberOfScans, observationDimension] = ...
        size(target);

    assert( ...
        prod(gridSize) == observationDimension, ...
        "ARES:InvalidLidarGrid", ...
        "Grid size does not match observation dimension.");

    %% Missingness and LiDAR-return statistics

    outageScanMask = ...
        any(missingMask, 2);

    validReturnFractionByScan = ...
        mean(validReturnMask, 2);

    degradedValidFractionByScan = ...
        mean(degradedValidReturnMask, 2);

    validRanges = ...
        target(validReturnMask);

    noReturnMask = ...
        ~validReturnMask;

    noReturnCount = ...
        nnz(noReturnMask);

    validReturnCount = ...
        nnz(validReturnMask);

    outageScanCount = ...
        nnz(outageScanMask);

    healthyScanCount = ...
        numberOfScans - outageScanCount;

    missingValueFraction = ...
        nnz(missingMask) / numel(missingMask);

    validReturnFraction = ...
        validReturnCount / numel(validReturnMask);

    noReturnFraction = ...
        noReturnCount / numel(validReturnMask);

    maximumRangeToleranceM = 1e-6;

    noReturnEncodedAtMaximumRange = ...
        mean( ...
            abs(target(noReturnMask) ...
                - maximumRangeM) ...
            <= maximumRangeToleranceM);

    outageEncodedAtMaximumRange = ...
        mean( ...
            abs(degraded(missingMask) ...
                - maximumRangeM) ...
            <= maximumRangeToleranceM);

    %% Low-rank exploratory analysis

    % This is EDA only. Do not reuse these statistics to transform test data.
    centeredTarget = ...
        target - mean(target, 1);

    % Use the scan Gram matrix instead of constructing a
    % 10740-by-10740 covariance matrix.
    gramMatrix = ...
        (centeredTarget * centeredTarget.') ...
        / max(numberOfScans - 1, 1);

    eigenvalues = sort( ...
        real(eig(gramMatrix)), ...
        "descend");

    eigenvalues(eigenvalues < 0) = 0;

    if sum(eigenvalues) > 0
        cumulativeExplainedVariance = ...
            cumsum(eigenvalues) ...
            / sum(eigenvalues);
    else
        cumulativeExplainedVariance = ...
            zeros(size(eigenvalues));
    end

    components90 = find( ...
        cumulativeExplainedVariance >= 0.90, ...
        1, ...
        "first");

    components95 = find( ...
        cumulativeExplainedVariance >= 0.95, ...
        1, ...
        "first");

    components99 = find( ...
        cumulativeExplainedVariance >= 0.99, ...
        1, ...
        "first");

    numericalTolerance = ...
        max(size(centeredTarget)) ...
        * eps(max(eigenvalues));

    empiricalRank = ...
        nnz(eigenvalues > numericalTolerance);

    %% Summary

    eda.numberOfScans = numberOfScans;
    eda.observationDimension = observationDimension;
    eda.healthyScanCount = healthyScanCount;
    eda.outageScanCount = outageScanCount;
    eda.missingValueFraction = missingValueFraction;
    eda.validReturnFraction = validReturnFraction;
    eda.noReturnFraction = noReturnFraction;

    eda.minimumValidRangeM = ...
        min(validRanges);

    eda.medianValidRangeM = ...
        median(validRanges);

    eda.meanValidRangeM = ...
        mean(validRanges);

    eda.maximumValidRangeM = ...
        max(validRanges);

    eda.noReturnEncodedAtMaximumRange = ...
        noReturnEncodedAtMaximumRange;

    eda.outageEncodedAtMaximumRange = ...
        outageEncodedAtMaximumRange;

    eda.empiricalRank = empiricalRank;
    eda.components90 = components90;
    eda.components95 = components95;
    eda.components99 = components99;

    summaryTable = table( ...
        numberOfScans, ...
        observationDimension, ...
        healthyScanCount, ...
        outageScanCount, ...
        missingValueFraction, ...
        validReturnFraction, ...
        noReturnFraction, ...
        empiricalRank, ...
        components90, ...
        components95, ...
        components99);

    fprintf("\nGRU episode EDA:\n");
    disp(summaryTable);

    fprintf( ...
        "Valid range: %.3f to %.3f m\n", ...
        eda.minimumValidRangeM, ...
        eda.maximumValidRangeM);

    fprintf( ...
        "Median valid range: %.3f m\n", ...
        eda.medianValidRangeM);

    fprintf( ...
        "No-returns encoded at maximum range: %.6f\n", ...
        noReturnEncodedAtMaximumRange);

    fprintf( ...
        "Outage values encoded at maximum range: %.6f\n", ...
        outageEncodedAtMaximumRange);

    %% Select representative scans

    firstOutageIndex = ...
        find(outageScanMask, 1, "first");

    assert(~isempty(firstOutageIndex), ...
        "ARES:NoOutageScans", ...
        "The episode contains no outage scans.");

    outageIndices = ...
        find(outageScanMask);

    representativeOutageIndex = ...
        outageIndices(round(numel(outageIndices) / 2));

    representativeHealthyIndex = ...
        max(firstOutageIndex - 1, 1);

    nominalOutageImage = reshape( ...
        target(representativeOutageIndex, :), ...
        gridSize);

    degradedOutageImage = reshape( ...
        degraded(representativeOutageIndex, :), ...
        gridSize);

    validReturnImage = reshape( ...
        validReturnMask( ...
            representativeOutageIndex, :), ...
        gridSize);

    %% Temporal EDA figure

    temporalFigure = figure( ...
        "Name", ...
        "GRU Episode Temporal EDA", ...
        "Color", ...
        "white");

    tiledlayout(3, 1, ...
        "TileSpacing", "compact", ...
        "Padding", "compact");

    nexttile;

    stairs( ...
        time_s, ...
        double(failureActive), ...
        "LineWidth", ...
        1.5);

    ylim([-0.1 1.1]);
    ylabel("Failure active");
    title("Intermittent LiDAR outage timeline");
    grid on;

    nexttile;

    plot( ...
        time_s, ...
        validReturnFractionByScan, ...
        "LineWidth", ...
        1.2);

    hold on;

    plot( ...
        time_s, ...
        degradedValidFractionByScan, ...
        "--", ...
        "LineWidth", ...
        1.2);

    ylabel("Valid-return fraction");
    legend( ...
        "Nominal target", ...
        "Degraded input", ...
        "Location", ...
        "best");

    grid on;

    nexttile;

    targetMeanByScan = ...
        mean(target, 2);

    degradedMeanByScan = ...
        mean(degraded, 2);

    plot( ...
        time_s, ...
        targetMeanByScan, ...
        "LineWidth", ...
        1.2);

    hold on;

    plot( ...
        time_s, ...
        degradedMeanByScan, ...
        "--", ...
        "LineWidth", ...
        1.2);

    xlabel("Time (s)");
    ylabel("Mean range (m)");

    legend( ...
        "Nominal target", ...
        "Degraded input", ...
        "Location", ...
        "best");

    grid on;

    exportgraphics( ...
        temporalFigure, ...
        fullfile( ...
            outputFolder, ...
            "gru_episode_temporal_eda.png"), ...
        "Resolution", ...
        180);

    %% Spatial and rank EDA figure

    spatialFigure = figure( ...
        "Name", ...
        "GRU Episode Spatial EDA", ...
        "Color", ...
        "white");

    tiledlayout(2, 2, ...
        "TileSpacing", "compact", ...
        "Padding", "compact");

    nexttile;

    imagesc(nominalOutageImage);
    axis tight;
    colorbar;
    clim([0 maximumRangeM]);

    title(sprintf( ...
        "Nominal target during outage, t = %.2f s", ...
        time_s(representativeOutageIndex)));

    xlabel("Azimuth index");
    ylabel("Elevation index");

    nexttile;

    imagesc(degradedOutageImage);
    axis tight;
    colorbar;
    clim([0 maximumRangeM]);

    title("Degraded input during outage");
    xlabel("Azimuth index");
    ylabel("Elevation index");

    nexttile;

    imagesc(validReturnImage);
    axis tight;
    colorbar;
    clim([0 1]);

    title("Nominal physical-return mask");
    xlabel("Azimuth index");
    ylabel("Elevation index");

    nexttile;

    plot( ...
        cumulativeExplainedVariance, ...
        "LineWidth", ...
        1.5);

    hold on;
    yline(0.90, "--");
    yline(0.95, "--");
    yline(0.99, "--");

    xlabel("Component count");
    ylabel("Cumulative explained variance");
    title("Exploratory effective dimensionality");
    ylim([0 1.01]);
    grid on;

    exportgraphics( ...
        spatialFigure, ...
        fullfile( ...
            outputFolder, ...
            "gru_episode_spatial_rank_eda.png"), ...
        "Resolution", ...
        180);

    %% Save numerical EDA results

    eda.time_s = time_s;
    eda.outageScanMask = outageScanMask;

    eda.validReturnFractionByScan = ...
        validReturnFractionByScan;

    eda.degradedValidFractionByScan = ...
        degradedValidFractionByScan;

    eda.eigenvalues = eigenvalues;

    eda.cumulativeExplainedVariance = ...
        cumulativeExplainedVariance;

    eda.representativeHealthyIndex = ...
        representativeHealthyIndex;

    eda.representativeOutageIndex = ...
        representativeOutageIndex;

    save( ...
        fullfile( ...
            outputFolder, ...
            "gru_episode_eda.mat"), ...
        "eda", ...
        "-v7.3");

    fprintf("EDA saved to: %s\n", outputFolder);
end