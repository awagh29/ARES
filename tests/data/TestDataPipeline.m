classdef TestDataPipeline < matlab.unittest.TestCase

    methods (Test)

        function contractIsValid(testCase)
            contract = ares.data.defaultDataContract();

            testCase.verifyEqual( ...
                contract.schemaVersion, ...
                "1.2.0");

            testCase.verifyEqual( ...
                contract.coordinateFrame, ...
                "NED");

            testCase.verifyNumElements( ...
                contract.dynamicFields, ...
                9);

            testCase.verifyNumElements( ...
                contract.enumerations ...
                .obstacleAvoidanceStatus, ...
                4);
        end

        function convertsVectorTimeseries(testCase)
            timeValues = (0:0.1:1)';

            expectedValues = single([
                timeValues
                2 * timeValues
                3 * timeValues
                ]);

            expectedValues = reshape( ...
                expectedValues, ...
                numel(timeValues), ...
                3);

            simulinkValues = reshape( ...
                expectedValues.', ...
                3, ...
                1, ...
                []);

            inputSeries = timeseries( ...
                simulinkValues, ...
                timeValues);

            signal = ares.data.timeseriesToSignal( ...
                inputSeries, ...
                3);

            testCase.verifySize( ...
                signal.values, ...
                [11 3]);

            testCase.verifyEqual( ...
                signal.values, ...
                expectedValues);

            testCase.verifyEqual( ...
                signal.time_s, ...
                timeValues);

            testCase.verifyEqual( ...
                signal.dataType, ...
                "single");
        end

        function rejectsIncorrectWidth(testCase)
            inputSeries = timeseries( ...
                zeros(3, 1, 5), ...
                (0:4)');

            testCase.verifyError( ...
                @() ares.data.timeseriesToSignal( ...
                inputSeries, ...
                2), ...
                "ARES:UnexpectedSignalWidth");
        end

    end
end