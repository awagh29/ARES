function organizedPoints = ...
    rangeImageToPointCloud( ...
        rangeM, ...
        validMask, ...
        deploymentConfig)
%RANGEIMAGETOPOINTCLOUD Convert reconstructed ranges to sensor-frame XYZ.
%
% rangeM:
%   15-by-716 reconstructed range image in meters.
%
% validMask:
%   15-by-716 logical valid-return mask.
%
% organizedPoints:
%   15-by-716-by-3 organized point cloud in the LiDAR sensor frame.
%   Invalid returns are represented by NaN.

arguments
    rangeM single
    validMask logical
    deploymentConfig struct
end

expectedSize = [ ...
    deploymentConfig.gridHeight, ...
    deploymentConfig.gridWidth];

assert(isequal(size(rangeM), expectedSize), ...
    "ARES:InvalidRangeImage", ...
    "Expected range image size %s, but received %s.", ...
    mat2str(expectedSize), ...
    mat2str(size(rangeM)));

assert(isequal(size(validMask), expectedSize), ...
    "ARES:InvalidValidityMask", ...
    "Expected validity-mask size %s, but received %s.", ...
    mat2str(expectedSize), ...
    mat2str(size(validMask)));

assert(all(isfinite(rangeM), "all"), ...
    "ARES:NonfiniteRange", ...
    "The reconstructed range image contains NaN or Inf.");

assert(all(rangeM >= 0, "all"), ...
    "ARES:NegativeRange", ...
    "The reconstructed range image contains negative ranges.");

% The sensor creates:
%   gridHeight elevation angles
%   gridWidth azimuth angles.
%
% RayGenerator3D uses evenly spaced angles across the configured limits.

azimuthDeg = linspace( ...
    double(deploymentConfig.azimuthLimitsDeg(1)), ...
    double(deploymentConfig.azimuthLimitsDeg(2)), ...
    deploymentConfig.gridWidth);

elevationDeg = linspace( ...
    double(deploymentConfig.elevationLimitsDeg(1)), ...
    double(deploymentConfig.elevationLimitsDeg(2)), ...
    deploymentConfig.gridHeight);

[azimuthGridDeg, elevationGridDeg] = meshgrid( ...
    azimuthDeg, ...
    elevationDeg);

azimuthGridDeg = single(azimuthGridDeg);
elevationGridDeg = single(elevationGridDeg);

% Unit ray directions in the LiDAR sensor frame.
directionX = ...
    cosd(elevationGridDeg) ...
    .* cosd(azimuthGridDeg);

directionY = ...
    cosd(elevationGridDeg) ...
    .* sind(azimuthGridDeg);

directionZ = ...
    sind(elevationGridDeg);

% Convert spherical ranges to Cartesian sensor-frame points.
pointX = rangeM .* directionX;
pointY = rangeM .* directionY;
pointZ = rangeM .* directionZ;

organizedPoints = cat( ...
    3, ...
    pointX, ...
    pointY, ...
    pointZ);

% Organized LiDAR output represents rays without returns using NaNs.
invalidRays = repmat( ...
    ~validMask, ...
    1, ...
    1, ...
    3);

organizedPoints(invalidRays) = single(NaN);

end