function [rangeM, validityProbability, validMask] = ...
    predictLidar( ...
        reconstructionNet, ...
        lidarHistory, ...
        contextHistory, ...
        deploymentConfig)
%PREDICTLIDAR Run the trained ARES LiDAR reconstruction network.
%
% Inputs
% ------
% reconstructionNet:
%   Imported and validated dlnetwork.
%
% lidarHistory:
%   Single array with size [1,10,3,15,716].
%
% contextHistory:
%   Single array with size [1,10,17].
%
% deploymentConfig:
%   Configuration stored in lidar_reconstruction_network.mat.
%
% Outputs
% -------
% rangeM:
%   Reconstructed 15-by-716 range image in meters.
%
% validityProbability:
%   Predicted 15-by-716 valid-return probabilities.
%
% validMask:
%   Thresholded 15-by-716 valid-return mask.

arguments
    reconstructionNet dlnetwork
    lidarHistory single
    contextHistory single
    deploymentConfig struct
end

expectedLidarSize = [ ...
    1, ...
    deploymentConfig.historyLength, ...
    deploymentConfig.lidarChannels, ...
    deploymentConfig.gridHeight, ...
    deploymentConfig.gridWidth];

expectedContextSize = [ ...
    1, ...
    deploymentConfig.historyLength, ...
    deploymentConfig.contextFeatures];

assert( ...
    isequal(size(lidarHistory), expectedLidarSize), ...
    "ARES:InvalidLidarHistory", ...
    "Expected lidarHistory size %s, but received %s.", ...
    mat2str(expectedLidarSize), ...
    mat2str(size(lidarHistory)));

assert( ...
    isequal(size(contextHistory), expectedContextSize), ...
    "ARES:InvalidContextHistory", ...
    "Expected contextHistory size %s, but received %s.", ...
    mat2str(expectedContextSize), ...
    mat2str(size(contextHistory)));

% MATLAB imported the LiDAR input as an unformatted tensor.
% Therefore, preserve its raw ONNX order:
% [batch,time,channel,height,width].
dlLidar = dlarray(lidarHistory);

% MATLAB expects context as:
% [feature,batch,time].
%
% Convert it from:
% [batch,time,feature].
contextMatlab = permute( ...
    contextHistory, ...
    [3 1 2]);

dlContext = dlarray( ...
    contextMatlab, ...
    "CBT");

% Run neural-network inference.
[dlRangeNormalized, dlValidityProbability] = predict( ...
    reconstructionNet, ...
    dlLidar, ...
    dlContext);

% Convert the network outputs back to ordinary MATLAB arrays.
rangeNormalized = single( ...
    gather(extractdata(dlRangeNormalized)));

validityProbability = single( ...
    gather(extractdata(dlValidityProbability)));

% Remove the singleton batch dimension.
rangeNormalized = squeeze(rangeNormalized);
validityProbability = squeeze(validityProbability);

% Keep outputs in their physically meaningful ranges.
rangeNormalized = min( ...
    max(rangeNormalized, single(0)), ...
    single(1));

validityProbability = min( ...
    max(validityProbability, single(0)), ...
    single(1));

% Convert normalized range to meters.
rangeM = rangeNormalized ...
    .* single(deploymentConfig.maximumRangeM);

% Determine which rays have valid predicted returns.
validMask = validityProbability ...
    >= single(deploymentConfig.validityThreshold);

end