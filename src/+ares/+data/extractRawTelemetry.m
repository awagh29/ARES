function telemetry = extractRawTelemetry(simOutput, manifest)

arguments
    simOutput (1,1) Simulink.SimulationOutput
    manifest (1,1) struct
end

contract = ares.data.defaultDataContract();

if ~isfield(manifest, "runId") || ...
        ~isfield(manifest, "schemaVersion")
    error("ARES:InvalidManifest", ...
        "Manifest requires runId and schemaVersion.");
end

if manifest.schemaVersion ~= contract.schemaVersion
    error("ARES:SchemaMismatch", ...
        "Manifest schema %s does not match contract schema %s.", ...
        manifest.schemaVersion, ...
        contract.schemaVersion);
end

outputNames = string(simOutput.who);

if ~any(outputNames == "logsout")
    error("ARES:MissingLogsout", ...
        "Simulation output does not contain logsout.");
end

logs = simOutput.logsout;
loggedNames = string(logs.getElementNames());

if ~isfield(contract, "requiredLoggedSignals")
    error("ARES:MissingRequiredLoggedSignalDefinition", ...
        "The data contract must define requiredLoggedSignals.");
end

requiredNames = string(contract.requiredLoggedSignals(:));

missingNames = setdiff(requiredNames, loggedNames, "stable");

if ~isempty(missingNames)
    error("ARES:MissingTelemetry", ...
        "Missing required signals: %s", strjoin(missingNames, ", "));
end

telemetry.schemaVersion = contract.schemaVersion;
telemetry.runId = manifest.runId;
telemetry.coordinateFrame = contract.coordinateFrame;
telemetry.timeBase = contract.timeBase;

telemetry.signals.position_ned_m = extractSignal( ...
    logs, "position_ned_m", 3, "m", ...
    ["north", "east", "down"]);

telemetry.signals.desired_position_ned_m = extractSignal( ...
    logs, "desired_position_ned_m", 3, "m", ...
    ["north", "east", "down"]);

telemetry.signals.velocity_ned_mps = extractSignal( ...
    logs, "velocity_ned_mps", 3, "m/s", ...
    ["north", "east", "down"]);

telemetry.signals.command_roll_rad = extractSignal( ...
    logs, "command_roll_rad", 1, "rad", "roll");

telemetry.signals.command_pitch_rad = extractSignal( ...
    logs, "command_pitch_rad", 1, "rad", "pitch");

telemetry.signals.command_yaw_rate_radps = extractSignal( ...
    logs, "command_yaw_rate_radps", 1, "rad/s", "yaw_rate");

telemetry.signals.command_thrust_n = extractSignal( ...
    logs, "command_thrust_n", 1, "N", "thrust");

telemetry.signals.lidar_enabled = extractSignal( ...
    logs, "lidar_enabled", 1, "boolean", "enabled");

if ~isfield(manifest, "static") || ...
        ~isfield( ...
        manifest.static, ...
        "maximum_sensor_range_m")

    error( ...
        "ARES:MissingMaximumLidarRange", ...
        "Manifest requires static.maximum_sensor_range_m.");
end

maximumRangeM = double(manifest.static.maximum_sensor_range_m);

[ ...
    telemetry.signals.nominal_lidar_ranges_m, ...
    telemetry.signals.nominal_lidar_valid_return_mask, ...
    telemetry.signals.nominal_observation, ...
    telemetry.lidarMetadata ...
    ] = extractOrganizedLidar( ...
    logs, ...
    "nominal_lidar_points_xyz_m", ...
    [15 716], ...
    maximumRangeM);

telemetry.signals.obstacle_avoidance_status = extractSignal( ...
    logs, "obstacle_avoidance_status", 1, "code", "status");

telemetry.contractCoverage.requiredLoggedSignals = requiredNames;

telemetry.contractCoverage.availableLoggedSignals = loggedNames;

telemetry.contractCoverage.dynamicFields = ...
    string(contract.dynamicFields(:));

telemetry.contractCoverage.directlyLoggedDynamicFields = ...
    intersect( ...
    telemetry.contractCoverage.dynamicFields, loggedNames, "stable");

telemetry.contractCoverage.nonLoggedDynamicFields = ...
    setdiff( ...
    telemetry.contractCoverage.dynamicFields, loggedNames, "stable");

telemetry.contractCoverage.requiredSignalsComplete = ...
    isempty(missingNames);

end

function signal = extractSignal( ...
    logs, signalName, expectedWidth, unitName, componentNames)

element = logs.getElement(signalName);

signal = ares.data.timeseriesToSignal( ...
    element.Values, ...
    expectedWidth);

signal.name = signalName;
signal.unit = unitName;
signal.components = componentNames;

end

function [ ...
    rangeSignal, ...
    validMaskSignal, ...
    nominalObservationSignal, ...
    metadata ...
] = extractOrganizedLidar( ...
    logs, ...
    signalName, ...
    lidarGridSize, ...
    maximumRangeM)

element = logs.getElement(signalName);
values = element.Values;

if ~isa(values, "timeseries")
    error( ...
        "ARES:InvalidLidarSignal", ...
        "LiDAR signal %s must be a timeseries.", ...
        signalName);
end

lidarTime = double(values.Time(:));
lidarXyz = double(values.Data);

numberOfScans = numel(lidarTime);
numberOfElevations = lidarGridSize(1);
numberOfAzimuths = lidarGridSize(2);
observationDimension = prod(lidarGridSize);

dataSize = size(lidarXyz);

if numel(dataSize) < 4
    error( ...
        "ARES:InvalidLidarDimensions", ...
        "LiDAR data requires XYZ and sample dimensions.");
end

if dataSize(1) ~= numberOfElevations || ...
        dataSize(2) ~= numberOfAzimuths || ...
        dataSize(3) ~= 3

    error( ...
        "ARES:InvalidLidarDimensions", ...
        [ ...
        "Expected LiDAR dimensions [%d %d 3 N], " ...
        "but received %s." ...
        ], ...
        numberOfElevations, ...
        numberOfAzimuths, ...
        mat2str(dataSize));
end

% Accommodate trailing singleton dimensions while preserving
% the organized elevation-azimuth-XYZ ordering.
lidarXyz = reshape( ...
    lidarXyz, ...
    numberOfElevations, ...
    numberOfAzimuths, ...
    3, ...
    []);

if size(lidarXyz, 4) ~= numberOfScans
    error( ...
        "ARES:LidarTimestampMismatch", ...
        [ ...
        "LiDAR contains %d scans but %d timestamps." ...
        ], ...
        size(lidarXyz, 4), ...
        numberOfScans);
end

rawRangeGrid = sqrt(sum( ...
    lidarXyz.^2, ...
    3));

rawRangeGrid = reshape( ...
    rawRangeGrid, ...
    numberOfElevations, ...
    numberOfAzimuths, ...
    numberOfScans);

finiteCoordinateMask = all( ...
    isfinite(lidarXyz), ...
    3);

finiteCoordinateMask = reshape( ...
    finiteCoordinateMask, ...
    numberOfElevations, ...
    numberOfAzimuths, ...
    numberOfScans);

rangeToleranceM = ...
    1e-6 * max(1, maximumRangeM);

validReturnGrid = ...
    finiteCoordinateMask & ...
    isfinite(rawRangeGrid) & ...
    rawRangeGrid > 0 & ...
    rawRangeGrid <= ...
        maximumRangeM + rangeToleranceM;

% Use maximum range as the numeric no-return representation.
% The logical mask retains the distinction between a valid
% measurement and an absent return.
filledRangeGrid = rawRangeGrid;

filledRangeGrid(validReturnGrid) = min( ...
    filledRangeGrid(validReturnGrid), ...
    maximumRangeM);

filledRangeGrid(~validReturnGrid) = ...
    maximumRangeM;

% MATLAB linear indexing makes elevation the fastest-changing
% dimension, followed by azimuth.
rangeMatrix = reshape( ...
    filledRangeGrid, ...
    observationDimension, ...
    numberOfScans)';

validMaskMatrix = reshape( ...
    validReturnGrid, ...
    observationDimension, ...
    numberOfScans)';

assert( ...
    isequal( ...
        size(rangeMatrix), ...
        [numberOfScans observationDimension]), ...
    "ARES:InvalidRangeMatrix", ...
    "Unexpected LiDAR range matrix size.");

assert( ...
    isequal( ...
        size(validMaskMatrix), ...
        [numberOfScans observationDimension]), ...
    "ARES:InvalidMaskMatrix", ...
    "Unexpected LiDAR mask matrix size.");

assert( ...
    all(isfinite(rangeMatrix), "all"), ...
    "ARES:NonfiniteNominalObservation", ...
    "The completed nominal observation must be finite.");

[elevationIndex, azimuthIndex] = ind2sub( ...
    lidarGridSize, ...
    (1:observationDimension)');

channelNames = compose( ...
    "lidar_e%02d_a%03d_range_m", elevationIndex, azimuthIndex);

rangeTimeseries = timeseries(rangeMatrix, lidarTime);

validMaskTimeseries = timeseries(validMaskMatrix, lidarTime);

rangeSignal = ares.data.timeseriesToSignal( ...
    rangeTimeseries, observationDimension);

rangeSignal.name = "nominal_lidar_ranges_m";

rangeSignal.unit = "m";
rangeSignal.components = channelNames';

validMaskSignal = ares.data.timeseriesToSignal( ...
    validMaskTimeseries, observationDimension);

validMaskSignal.name = "nominal_lidar_valid_return_mask";

validMaskSignal.unit = "logical";
validMaskSignal.components = channelNames';

% For the first baseline, the observation consists only of
% the fixed-dimensional LiDAR range vector.
nominalObservationSignal = rangeSignal;

nominalObservationSignal.name = "nominal_observation";

metadata.gridSize = lidarGridSize;
metadata.observationDimension = observationDimension;
metadata.numberOfScans = numberOfScans;
metadata.maximumRangeM = maximumRangeM;
metadata.channelOrder = ...
    "elevation-index-fastest-then-azimuth-index";
metadata.validReturnCount = nnz(validMaskMatrix);
metadata.totalBeamCount = numel(validMaskMatrix);
metadata.validReturnFraction = ...
    metadata.validReturnCount / ...
    metadata.totalBeamCount;
metadata.invalidReturnCount = ...
    metadata.totalBeamCount - ...
    metadata.validReturnCount;

end