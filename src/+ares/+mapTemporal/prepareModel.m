function prepared = prepareModel(projectRoot,options)
%PREPAREMODEL Export/validate selected weights and save a standalone mission.
arguments
    projectRoot (1,1) string
    options (1,1) struct = struct()
end
options=ares.mapTemporal.validateOptions(options);
baseline=fullfile(projectRoot,'models','ares_single_uav_top.slx');
baselineHash=ares.inference.fileSha256(baseline);
model="ares_single_uav_map_temporal_cnn";
if bdIsLoaded(model)
    assert(string(get_param(model,'SimulationStatus'))=="stopped" && string(get_param(model,'Dirty'))=="off", ...
        'ARES:TemporalModelHasEdits','Stop and save the open map-temporal model before preparing another mission.');
    close_system(model,0);
end
assert(~bdIsLoaded('ares_single_uav_top') || ...
    string(get_param('ares_single_uav_top','SimulationStatus'))=="stopped", ...
    'ARES:BaselineRunning','Stop the baseline simulation before initializing another scene.');
artifact=ares.mapTemporal.resolveArtifact(projectRoot,options);
options.ModelPath=artifact.SourcePath;
folder=fullfile(projectRoot,'results','map_temporal_simulation',string(java.util.UUID.randomUUID()));
mkdir(folder); planFile=fullfile(folder,'mission.mat');
[map,cfg,schedule,intervals]=ares.mapTemporal.initializeSimulation(projectRoot,planFile,options);
data=load(artifact.Path,'model');
native=data.model;
assert(abs(double(native.maxRange)-7)<1e-8 && abs(double(native.samplePeriodS)-.1)<1e-8 && ...
    isequal(size(native.raysSensor),[10740 3]) && ...
    max(abs(double(native.raysSensor)-map.SensorDirections),[],'all')<5e-6 && ...
    max(abs(double(native.raysBody)-map.SensorDirections*map.SensorToBodyRotation'),[],'all')<5e-6 && ...
    norm(double(native.mountingTranslation(:))-map.SensorMountBodyM(:))<1e-6, ...
    'ARES:TemporalSensorMismatch','Checkpoint range, scan period, beam order or mounting differs from this LiDAR.');
assert(all(options.WorldBoundsNedM(:,1)>=native.worldBounds(:,1)) && ...
    all(options.WorldBoundsNedM(:,2)<=native.worldBounds(:,2)), ...
    'ARES:TemporalCheckpointDomain','Requested world bounds exceed this checkpoint training domain.');
actual=[(map.BoxMin+map.BoxMax)/2,map.BoxMax-map.BoxMin];
assert(isequal(single(sortrows(actual)),sortrows(data.model.obstacles)), ...
    'ARES:TemporalObstacleMapMismatch','Checkpoint obstacle map differs from the simulated scene.');
for name=["StartState","GoalState"]
    state=options.(name); delta=max(max(map.BoxMin-state(1:3),state(1:3)-map.BoxMax),0);
    clearance=min(vecnorm(delta,2,2))-options.VehicleRadiusM;
    assert(clearance>=options.MinimumSurfaceClearanceM,'ARES:TemporalEndpointClearance', ...
        '%s has %.3f m surface clearance; require %.3f m. Choose a free endpoint.', ...
        name,clearance,options.MinimumSurfaceClearanceM);
end
save(planFile,'options','map','cfg','intervals','artifact');
modelPath=fullfile(folder,model+'.slx'); copyfile(baseline,modelPath); load_system(modelPath);
try
    wiring=ares.mapTemporal.configureModel(model,artifact.Path,planFile,options);
    rootQuoted="'"+replace(projectRoot,"'","''")+"'";
    planQuoted="'"+replace(planFile,"'","''")+"'";
    set_param(model,'InitFcn',"ares.mapTemporal.initializeSimulation("+rootQuoted+","+planQuoted+");",'StopFcn','');
    set_param(model,'SimulationCommand','update'); save_system(model,modelPath);
catch exception
    if bdIsLoaded(model), close_system(model,0); end
    rethrow(exception);
end
assert(ares.inference.fileSha256(baseline)==baselineHash,'ARES:BaselineChanged','Baseline changed.');
prepared=struct('SchemaVersion',"ares-map-temporal-preparation-v1", ...
    'ProjectRoot',projectRoot,'ModelName',model,'ModelPath',modelPath,'PlanFile',planFile, ...
    'BaselineSha256',baselineHash,'PreparedModelSha256',ares.inference.fileSha256(modelPath), ...
    'MissionSha256',ares.inference.fileSha256(planFile),'Options',options,'Artifact',artifact, ...
    'OutageIntervalsS',intervals,'ScheduleTimeS',double(schedule.Time), ...
    'ScheduleEnabled',double(schedule.Data),'Wiring',wiring);
files=dir(fullfile(projectRoot,'src','+ares','+mapTemporal','*.m'));
paths=["scripts/initializeSingleUav.m";"src/+ares/+config/defaultSingleUav.m"; ...
    "src/+ares/+config/configureSimulinkCache.m"; ...
    "src/+ares/+inference/configureSparseReconstructionModel.m"; ...
    "src/+ares/+inference/sectorFeatures.m";"src/+ares/+data/evaluateAxisRun.m"; ...
    "src/+ares/+data/timeseriesToSignal.m";"src/+ares/+navigation/defaultOptions.m"; ...
    "src/+ares/+navigation/validateOptions.m";"src/+ares/+navigation/outageSchedule.m"; ...
    "src/+ares/+navigation/sceneMap.m";"src/+ares/+mapTemporal/"+string({files.name})'];
prepared.RuntimeSources=struct('Path',{},'Sha256',{});
for k=1:numel(paths)
    prepared.RuntimeSources(k)=struct('Path',paths(k),'Sha256',ares.inference.fileSha256(fullfile(projectRoot,paths(k))));
end
ares.mapTemporal.writeJson(fullfile(folder,'prepared.json'),prepared);
ares.mapTemporal.writeJson(fullfile(projectRoot,'results','map_temporal_simulation','latest_prepared.json'),prepared);
assignin('base','mapTemporalPrepared',prepared);
if options.ShowSimulation, open_system(model); end
fprintf('Prepared map-temporal simulation; %d scheduled outage(s).\nSelected model: %s\nSaved simulation: %s\n', ...
    size(intervals,1),artifact.SourcePath,modelPath);
end
