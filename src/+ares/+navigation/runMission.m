function result = runMission(prepared)
%RUNMISSION Simulate a prepared mission and save state/command/outage evidence.
data=load(prepared.PlanFile,'options','map','cfg','plan'); o=data.options;
baseline=fullfile(prepared.ProjectRoot,'models','ares_single_uav_top.slx');
assert(ares.inference.fileSha256(baseline)==prepared.BaselineSha256,'ARES:MapBaselineChanged','Baseline changed since preparation.');
assert(ares.inference.fileSha256(prepared.ModelPath)==prepared.PreparedModelSha256, ...
    'ARES:MapPreparedModelChanged','Prepared model changed. Prepare a new mission to record its executed wiring.');
assert(ares.inference.fileSha256(prepared.PlanFile)==prepared.MissionSha256, ...
    'ARES:MapMissionChanged','Saved mission inputs changed. Prepare the mission again.');
for source=prepared.RuntimeSources
    assert(ares.inference.fileSha256(fullfile(prepared.ProjectRoot,source.Path))==source.Sha256, ...
        'ARES:MapRuntimeChanged','Source changed since preparation: %s. Prepare the mission again.',source.Path);
end
load_system(prepared.ModelPath);
timer=tic; simOut=sim(prepared.ModelName); wall=toc(timer);
packet=simOut.logsout.getElement('map_runtime_packet').Values;
sample=ares.data.timeseriesToSignal(packet,43);
time=double(sample.time_s(:)); values=double(sample.values);
position=simOut.logsout.getElement('position_ned_m').Values;
velocity=simOut.logsout.getElement('velocity_ned_mps').Values;
telemetry.signals.position_ned_m=ares.data.timeseriesToSignal(position,3);
telemetry.signals.velocity_ned_mps=ares.data.timeseriesToSignal(velocity,3);
centers=(data.map.BoxMin+data.map.BoxMax)/2;
metrics=ares.data.evaluateAxisRun(telemetry,data.cfg,centers,3,15);
expected=interp1(prepared.ScheduleTimeS,prepared.ScheduleEnabled,time,'previous')>=.5;
proof=struct('AvailabilityMatchesSchedule',isequal(logical(values(:,20)),expected), ...
    'EveryOutageUsesMapCorrection',all(values(~expected,21)==1), ...
    'EveryHealthyTickUsesMeasuredLidar',all(values(expected,21)==0), ...
    'AllFiltersFeasible',all(values(:,22)==1),'MapAvailableEveryTick',all(values(:,29)==1));
actualVelocity=double(telemetry.signals.velocity_ned_mps.values);
goalAtTermination=logical(values(end,26));
proof.InitialVelocityMatchesRequest=norm(actualVelocity(1,:)-o.StartState(4:6))<1e-4;
metrics.goalReachedAtTermination=metrics.goalReachedAtTermination && goalAtTermination;
metrics.missionSuccess=metrics.missionSuccess && goalAtTermination && proof.AllFiltersFeasible && ...
    proof.AvailabilityMatchesSchedule && proof.InitialVelocityMatchesRequest;
if ~proof.AllFiltersFeasible, metrics.terminationReason="map-filter-infeasible-or-invalid";
elseif ~goalAtTermination && metrics.reachedTimeLimit, metrics.terminationReason="time-limit-before-terminal-state";
end
result=struct('SchemaVersion',"ares-map-correction-run-v1", ...
    'ModelPath',prepared.ModelPath,'PlanFile',prepared.PlanFile,'LidarMode',o.LidarMode, ...
    'PlannedOutageCount',size(prepared.OutageIntervalsS,1), ...
    'ObservedOutageCount',double(~expected(1))+nnz(diff(expected)==-1), ...
    'OutageControlTicks',nnz(~expected),'ControlTicks',numel(time), ...
    'ArrivalTimeS',time(end),'WallTimeS',wall,'Metrics',metrics,'Proof',proof, ...
    'MaximumBarrierViolation',max(values(:,23)), ...
    'MinimumBarrierH',min(values(:,24)),'MinimumBarrierPsi1',min(values(:,25)), ...
    'MaximumControlComputeS',max(values(:,28)),'SafetyCertified',false);
result.Directory=string(fileparts(prepared.PlanFile));
names=["roll_rad","pitch_rad","yaw_rate_radps","thrust_n", ...
    "accel_n","accel_e","accel_d","nominal_accel_n","nominal_accel_e","nominal_accel_d", ...
    "reference_n","reference_e","reference_d","position_n","position_e","position_d", ...
    "velocity_n","velocity_e","velocity_d","lidar_available","map_outage_correction_used", ...
    "filter_feasible","constraint_violation","minimum_h","minimum_psi1", ...
    "terminal_state_reached","waypoint_index","compute_seconds","map_available", ...
    compose("selected_sector_%02d",1:14)];
scans=array2table([time values],'VariableNames',["time_s",names]);
writetable(scans,fullfile(result.Directory,'control.csv'));
save(fullfile(result.Directory,'telemetry.mat'),'telemetry','scans','prepared','result','-v7.3');
fid=fopen(fullfile(result.Directory,'summary.json'),'w');
assert(fid>=0,'ARES:MapWriteFailed','Cannot write run summary.');
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',jsonencode(result,PrettyPrint=true));
assert(ares.inference.fileSha256(baseline)==prepared.BaselineSha256,'ARES:BaselineChanged','Baseline changed during run.');
assignin('base','mapCorrectionResult',result);
fprintf('Goal reached at rest: %d. Mission success: %d. Time: %.2f s. Minimum surface clearance: %.3f m.\n', ...
    goalAtTermination,metrics.missionSuccess,time(end),metrics.minimumObstacleClearanceM);
fprintf('Observed/planned outages: %d/%d. Results: %s\n',result.ObservedOutageCount,result.PlannedOutageCount,result.Directory);
end
